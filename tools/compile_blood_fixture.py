#!/usr/bin/env python3
"""data/blood_fixture.json -> build/blood_fixture.h (tools/test_neo_blood.c)."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
d=json.loads((ROOT/'data/blood_fixture.json').read_text())
lines=['/* Generated by tools/compile_blood_fixture.py; do not edit. */','#include <stdint.h>',
       'typedef struct { uint32_t site; uint16_t on,off; unsigned requests; } blood_site_t;','static const blood_site_t blood_sites[]={']
for s in d['sites']:
    assert s['on'] and s['on_requests']>0,s
    lines.append('  {%s,%s,%s,%d},'%(s['site'],s['on'],s['off'],s['on_requests']))
lines.append('};')
(ROOT/'build').mkdir(exist_ok=True);(ROOT/'build/blood_fixture.h').write_text('\n'.join(lines)+'\n')
