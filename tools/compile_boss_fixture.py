#!/usr/bin/env python3
"""Compile data/boss_fight_*.json.gz (tools/extract_boss_fight.py) into
build/boss_fixture.h: one little-endian byte stream per fight, read by
tools/test_neo_boss.c (format documented there)."""
import gzip,json,struct,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
EV={'rng':1,'alloc':2,'pal':3,'scene':4,'sweep':5,'floor':6,'plat':7,'platfree':8,'hurt':9,'attack':10,'bounds':11,'draw':12,'mission':13}
def s32(v):return v-(1<<32) if v>=1<<31 else v
def u32(v):return v&0xffffffff
def fight(path):
    d=json.load(gzip.open(path))
    o=bytearray()
    o+=struct.pack('<HI',len(d['nodes']),len(d['updates']))
    for n in d['nodes']:o+=struct.pack('<IhI',n['ctor'],n['creator'],n['addr'])
    for u in d['updates']:
        pre=u.get('pre')
        o+=struct.pack('<IHIBi',u['f'],u['n'],u['r'],1 if pre else 0,u.get('handoff',0) or 0)
        if pre:o+=bytes.fromhex(pre)
        o+=bytes.fromhex(u['post'])
        o+=struct.pack('<H',len(u['hits']))
        for h in u['hits']:
            att=bytes.fromhex(h['attacker']) if h['attacker'] else bytes(0xb0)
            o+=struct.pack('<HHHIB',h['node'],h['kind'] if h['kind'] is not None else 0xffff,h['d3']&0xffff,h['d3']>>16,1 if h['attacker'] else 0)
            o+=att
            o+=struct.pack('<H',len(h['writes']))
            for off,v,pc in h['writes']:o+=struct.pack('<BBI',off,v,pc)
        env=u.get('env',{})
        o+=struct.pack('<B',len(env))
        for k,v in env.items():o+=struct.pack('<IB',int(k,16),v)
        o+=struct.pack('<H',len(u['ev']))
        for e in u['ev']:
            k=e[0];o+=struct.pack('<B',EV[k])
            if k=='rng':o+=struct.pack('<H',e[1])
            elif k=='alloc':
                exp=e[5] if len(e)>5 else None
                o+=struct.pack('<Hhh',e[1],-2 if e[2] is None else e[3],(1 if e[4] else 0)|(2 if exp else 0))
                if e[4]:o+=bytes.fromhex(e[4])
                if exp:o+=bytes.fromhex(exp)
            elif k=='pal':o+=struct.pack('<B',e[1])
            elif k=='scene':o+=struct.pack('<IIIIIB',u32(e[1]),u32(e[2]),u32(e[3]),u32(e[4] or 0),u32(e[5] or 0),e[6] or 0)
            elif k=='sweep':
                w=e[1];x,y,vx,vy,par=(w[0]<<16|w[1],w[2]<<16|w[3],w[4]<<16|w[5],w[6]<<16|w[7],w[8]<<16|w[9])
                f15,f5f=e[2],e[3];fl=(1 if f15&0x40 else 0)|(2 if f15&0x80 else 0)|(4 if f5f&1 else 0)|(8 if f5f&4 else 0)|(16 if f5f&2 else 0)|(128 if f5f&0x80 else 0)
                o+=struct.pack('<IIIIIHH',x,y,vx,vy,par,fl,e[4])
            elif k=='floor':
                w=e[1];o+=struct.pack('<IIIH',w[0]<<16|w[1],w[2]<<16|w[3],w[8]<<16|w[9],e[2])
            elif k=='plat':
                vals=e[2];longs=[vals[i]<<16|vals[i+1] for i in range(0,len(vals)-1,2)]
                o+=struct.pack('<BB',0xff if e[1] is None else e[1],len(longs))+b''.join(struct.pack('<I',v) for v in longs)
            elif k=='platfree':pass
            elif k=='hurt':o+=struct.pack('<BBB',e[2] or 0,e[3] or 0,e[4])
            elif k=='attack':o+=struct.pack('<H',e[1])
            elif k=='bounds':o+=struct.pack('<IIIIHHHH',u32(e[1]),u32(e[2]),u32(e[3]),u32(e[4]),e[5],e[6],e[7],e[8])
            elif k=='draw':
                w=e[1]+[0]*6;o+=struct.pack('<IHHHH',u32(w[4]<<16|w[5]),w[0],w[1],w[3],e[2]&0xffff)
            elif k=='mission':o+=struct.pack('<B',e[1])
    return d['name'],bytes(o)
L=['/* Generated by tools/compile_boss_fixture.py; do not edit. */','#ifndef BOSS_FIXTURE_H','#define BOSS_FIXTURE_H','#include <stdint.h>']
names=[]
for p in sorted((ROOT/'data').glob('boss_fight_*.json.gz')):
    name,b=fight(p);names.append(name)
    # the same stream for the MIPS cartridge (boss-regression.z64, DFS)
    (ROOT/'build/boss-romfs').mkdir(parents=True,exist_ok=True);(ROOT/f'build/boss-romfs/boss-{name}.bin').write_bytes(b)
    L.append('static const uint8_t boss_fight_%s[]={%s};'%(name,','.join(map(str,b))))
L.append('typedef struct { const char *name; const uint8_t *bytes; uint32_t size; } boss_fight_t;')
L.append('static const boss_fight_t boss_fights[]={%s};'%','.join('{"%s",boss_fight_%s,sizeof(boss_fight_%s)}'%(n,n,n) for n in names))
L.append('#endif')
(ROOT/'build/boss_fight_names.h').write_text('/* Generated by tools/compile_boss_fixture.py */\n#define BOSS_FIGHT_NAMES %s\n'%','.join('"%s"'%n for n in names))
(ROOT/'build').mkdir(exist_ok=True);(ROOT/'build/boss_fixture.h').write_text('\n'.join(L)+'\n')
print(names)
