#!/usr/bin/env python3
"""Compile data/camera_fixture.json.gz into build/camera_fixture.h."""
import gzip,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
d=json.load(gzip.open(ROOT/'data/camera_fixture.json.gz','rt'))
L=['/* Generated by tools/compile_camera_fixture.py; do not edit. */','#ifndef CAMERA_FIXTURE_H','#define CAMERA_FIXTURE_H','#include <stdint.h>',
   'typedef struct { uint32_t frame; uint8_t players[2][3]; uint16_t words[2][2]; uint8_t follow;',
   '  uint8_t auto_mode,auto_owner; int32_t auto_vx,auto_vy; uint16_t command; int32_t root_vx,root_vy,root_x,root_y,x,y,dx,dy;',
   '  uint32_t progress,target; int32_t path_x,path_y; int16_t bounds[4]; uint16_t mode,p69b8,p69ba; uint32_t lock; int16_t lock_bounds[4];',
   '  int32_t shake,shake_applied; uint16_t restart; int16_t view[4]; } camera_record_t;',
   'static const camera_record_t camera_records[]={']
def s16(v):return v-65536 if v>=32768 else v
for r in d['records']:
    p=r['players']
    L.append('{%d,{{%d,%d,%d},{%d,%d,%d}},{{%d,%d},{%d,%d}},%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%du,%du,%d,%d,{%s},%d,%d,%d,%du,{%s},%d,%d,%d,{%s}},'%(
        r['frame'],p[0][0],p[0][1],p[0][2],p[1][0],p[1][1],p[1][2],p[0][3],p[0][4],p[1][3],p[1][4],r['follow'],r['auto_mode'],r['auto_owner'],r['auto_vx'],r['auto_vy'],
        r['command'],r['root_vx'],r['root_vy'],r['root_x'],r['root_y'],r['x'],r['y'],r['dx'],r['dy'],r['progress'],r['target'],r['path_x'],r['path_y'],
        ','.join(str(s16(v&0xffff)) for v in r['bounds']),r['mode'],r['p69b8'],r['p69ba'],r['lock'],','.join(str(v) for v in r['lock_bounds']),
        r['shake'],r['shake_applied'],r['restart'],','.join(str(v) for v in r['view'])))
L+=['};','#endif']
(ROOT/'build').mkdir(exist_ok=True);(ROOT/'build/camera_fixture.h').write_text('\n'.join(L)+'\n')
print(len(d['records']),'camera records')
