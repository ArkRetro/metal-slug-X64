#!/usr/bin/env python3
"""data/continue_fixture.json.gz -> build/continue_fixture.h (tools/test_neo_continue.c)."""
import gzip,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
src=Path(sys.argv[1]) if len(sys.argv)>1 else ROOT/'data/continue_fixture.json.gz'
out=Path(sys.argv[2]) if len(sys.argv)>2 else ROOT/'build/continue_fixture.h'
d=json.load(gzip.open(src,'rt'))
caps=[];ups=[];words=[]
for c in d:
    caps.append('{"%s",%d,%d,%d,%d,%d,%d,{%s}}'%(c['name'],c['start'],len(ups),len(c['updates']),c['dip8a'],int(c['mvs']),c['join'],
        ','.join('0x'+c['score'][k:k+2] for k in range(0,8,2))))
    words+=c['initial']
    for u in c['updates']:
        ups.append('{%d,%d,%d,%d,%d,%d,%d,%d,{%s},%d}'%(u['frame'],int(u['hud_on']),u['credits'],int(u['start']),int(u['b']),
            u['timer'],u['mode'],u['lives'],','.join('0x'+u['score'][k:k+2] for k in range(0,8,2)),len(words)))
        words+=u['region']
out.parent.mkdir(parents=True,exist_ok=True)
with open(out,'w') as o:
    o.write('/* Generated by tools/compile_continue_fixture.py from %s. */\n'%src.name)
    o.write('typedef struct {const char *name;unsigned start,first,count,dip8a,mvs,join;unsigned char score[4];} cont_capture_t;\n')
    o.write('typedef struct {unsigned frame,hud_on,credits,start,b,timer,mode,lives;unsigned char score[4];unsigned region;} cont_update_t;\n')
    o.write('#define CONT_CAPTURES %d\nstatic const cont_capture_t cont_captures[]={%s};\n'%(len(caps),',\n'.join(caps)))
    o.write('static const cont_update_t cont_updates[]={\n%s};\n'%',\n'.join(ups))
    o.write('static const unsigned short cont_words[]={%s};\n'%','.join(map(str,words)))
