#!/usr/bin/env python3
"""C header of the credits' world fixture (tools/extract_credits_world.py) for tools/test_neo_credits.c."""
import argparse,gzip,json
from pathlib import Path
p=argparse.ArgumentParser(description=__doc__);p.add_argument('fixture',type=Path);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
d=json.load(gzip.open(a.fixture))
L=['/* Generated by tools/compile_credits_world.py from %s. */'%a.fixture.name]
L.append('static const uint16_t credits_ring[55]={%s};'%','.join(map(str,d['ring'])))
L.append('enum { CREDITS_CURSOR=%d, CREDITS_LIVES=%d, CREDITS_PASSES=%d };'%(d['cursor'],len(d['creators']),len(d['passes'])))
L.append('static const int16_t credits_creators[]={%s};'%','.join(map(str,d['creators'])))
L.append('static const uint8_t credits_first[][0xb0]={')
for h in d['first']:
    b=bytes.fromhex(h or '00'*0xb0);L.append('{'+','.join(map(str,b))+'},')
L.append('};')
ups=[];L.append('static const struct {uint32_t frame;uint32_t first;uint16_t count;uint8_t held;} credits_passes[]={')
for ps in d['passes']:
    L.append('{%d,%d,%d,%d},'%(ps['frame'],len(ups),len(ps['updates']),ps['held']));ups+=ps['updates']
L.append('};')
L.append('static const struct {int16_t life;uint8_t has_post;uint32_t routine,pre,post;} credits_updates[]={')
for u in ups:L.append('{%d,%d,0x%x,0x%xu,0x%xu},'%(u['life'],u['post'] is not None,u['routine'],u['pre'],u['post'] or 0))
L.append('};')
a.output.write_text('\n'.join(L)+'\n')
