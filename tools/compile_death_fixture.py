#!/usr/bin/env python3
"""data/death_fixture.json -> build/death_fixture.h (tools/test_marco_death.c)."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
d=json.load(open(ROOT/'data/death_fixture.json'))
out=ROOT/'build/death_fixture.h';out.parent.mkdir(parents=True,exist_ok=True)
deaths=[];ups=[];poses=[]
for x in d['deaths']:
    deaths.append('{%d,%d,%d,%d,%d,%d,%d,%d,%d}'%(x['frame'],x['progress'],x['kind'],x['f5b'],len(ups),len(x['updates']),len(poses),len(x.get('dying_poses',[])),x.get('lying_draws',0)))
    poses+=x.get('dying_poses',[])
    for u in x['updates']:
        r,f15,vx,vy,x3c,y40,x28,y2c,p38,f26=u[:10];desc=u[10] if len(u)>10 else 0
        ups.append('{0x%s,%d,%du,%du,%du,%du,%du,%du,0x%s,%d,0x%x}'%(r,f15,vx,vy,x3c,y40,x28,y2c,p38,f26,desc))
with open(out,'w') as o:
    o.write('/* Generated by tools/compile_death_fixture.py (%s). */\n'%d['source'])
    o.write('typedef struct {unsigned frame,progress,kind,f5b,first,count,pose_first,pose_count,lying_draws;} death_case_t;\n')
    o.write('typedef struct {unsigned routine,f15;unsigned v30,v34,x3c,y40,x28,y2c,p38,f26,descriptor;} death_update_t;\n')
    o.write('#define DEATHS %d\nstatic const death_case_t death_cases[]={%s};\n'%(len(deaths),',\n'.join(deaths)))
    o.write('static const death_update_t death_updates[]={\n%s};\n'%',\n'.join(ups))
    o.write('static const unsigned death_poses[]={%s};\n'%(','.join('0x%x'%v for v in poses) or '0'))
print(len(deaths),'deaths',len(ups),'updates ->',out)
