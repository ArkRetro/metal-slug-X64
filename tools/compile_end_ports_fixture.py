#!/usr/bin/env python3
"""data/end_ports_fixture.json.gz (tools/extract_end_ports_fixture.py) -> build/end_ports_fixture.h."""
import argparse,gzip,json
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('fixture',type=Path);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
d=json.load(gzip.open(a.fixture))
rows=d['rows']
out=['/* Generated by tools/compile_end_ports_fixture.py. */','enum { END_PORTS_HELD_BEFORE=%d, END_PORTS_COUNT_BEFORE=%d, END_PORTS_DELAY=%d, END_PORTS_REPEAT=%d, END_PORTS_ROWS=%d };'%(d['held_before'],d['count_before'],d['delay'],d['repeat'],len(rows)),
     '/* update, held, new presses, repeat byte and count (-1: not read by the node) */','static const int end_ports_rows[][5]={']
out+=['{%d,%d,%d,%d,%d},'%(r['update'],r['held'],r['new'],r.get('repeat',-1),r.get('count',-1)) for r in rows]
out.append('};')
a.output.write_text('\n'.join(out)+'\n')
