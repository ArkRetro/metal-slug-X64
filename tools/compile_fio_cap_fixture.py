#!/usr/bin/env python3
"""data/fio_cap_fixture.json (tools/extract_fio_cap_fixture.py) ->
build/fio_cap_fixture.h (tools/test_fio_cap.c)."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
d=json.load(open(ROOT/'data/fio_cap_fixture.json'))
rows=',\n'.join('{%d,%d,%du,%du,%du,%d,%d}'%tuple(u) for u in d['updates'])
out=ROOT/'build/fio_cap_fixture.h';out.parent.mkdir(parents=True,exist_ok=True)
out.write_text('/* Generated by tools/compile_fio_cap_fixture.py (%s). */\n'%d['source']+
 'typedef struct {unsigned f15,f26;unsigned v30,v34,p38,f5f,f80;} cap_update_t;\n'+
 '#define CAP_UPDATES %du\nstatic const unsigned cap_creator_v30=%du,cap_creator_v34=%du;\nstatic const cap_update_t cap_updates[]={\n%s};\n'%(len(d['updates']),d['creator_v30'],d['creator_v34'],rows))
print(len(d['updates']),'updates ->',out)
