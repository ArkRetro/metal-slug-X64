#!/usr/bin/env python3
"""data/hgun_fixture.json -> build/hgun_fixture.h (tools/test_marco_hgun.c)."""
import json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
d=json.load(open(ROOT/'data/hgun_fixture.json'))
out=ROOT/'build/hgun_fixture.h';out.parent.mkdir(parents=True,exist_ok=True)
rows=[]
for f,inp,f15,a92,a95,b in d['frames']:
    bits=sum(1<<i for i,c in enumerate('LRUABC') if c in inp)
    rows.append('{%d,%d,%d,%d,%d,%d,{%s}}'%(f,bits,f15,a92,a95,len(b),','.join(map(str,b[:4])) or '0'))
with open(out,'w') as o:
    o.write('/* Generated by tools/compile_hgun_fixture.py (%s). inputs: bit 0 L, 1 R, 2 U, 3 A, 4 B, 5 C. */\n'%d['source'])
    o.write('typedef struct {unsigned frame,inputs,f15,f92,f95,births;unsigned char angle[4];} hgun_row_t;\n')
    o.write('#define HGUN_ROWS %d\nstatic const hgun_row_t hgun_rows[]={\n%s};\n'%(len(rows),',\n'.join(rows)))
print(len(rows),'rows ->',out)
