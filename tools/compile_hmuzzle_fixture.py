#!/usr/bin/env python3
"""data/hmuzzle_fixture.json -> build/hmuzzle_fixture.h (tools/test_marco_muzzle.c)."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
d=json.load(open(ROOT/'data/hmuzzle_fixture.json'))
rows=['{%d,0x%s,%d,%d,%d,%d,%d,%d,0x%x}'%(f,r,face,ground,f92,ang,dx,dy,b) for cap,f,r,face,ground,f92,ang,dx,dy,b in d['births']]
out=ROOT/'build/hmuzzle_fixture.h';out.parent.mkdir(parents=True,exist_ok=True)
out.write_text('/* Generated by tools/compile_hmuzzle_fixture.py (%s). */\ntypedef struct {unsigned frame,routine,left,ground,f92,angle;int dx,dy;unsigned bullet;} hbirth_t;\n#define HBIRTHS %d\nstatic const hbirth_t hbirths[]={%s};\n'%(d['source'],len(rows),',\n'.join(rows)))
print(len(rows),'births ->',out)
