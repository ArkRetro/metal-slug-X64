#!/usr/bin/env python3
"""data/hud_fixture.json.gz -> build/hud_fixture.h (tools/test_neo_hud.c)."""
import gzip,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
src=Path(sys.argv[1]) if len(sys.argv)>1 else ROOT/'data/hud_fixture.json.gz'
out=Path(sys.argv[2]) if len(sys.argv)>2 else ROOT/'build/hud_fixture.h'
d=json.load(gzip.open(src,'rt'))
iv=[];words=[];steps=[];names=[]
for ci,c in enumerate(d['captures']):
    names.append(c['name'])
    for i in c['intervals']:
        f=i['flags'];g=i['flags0']
        iv.append('{%d,%d,%d,%d,%d,%d,{%s},{%d,%d},%d,%d,%d,{%s},%d,{%d,%d,%d,%d,%d,%d,%d,%d,%d,%d},{%d,%d,%d,%d},%d}'%(
            ci,int(c['frozen']),i['f0'],i['f1'],len(words),len(steps),
            ','.join('{%s}'%','.join(map(str,p)) for p in i['panel']),i['blink'][0],i['blink'][1],
            i['timer'],i['video'],i['video1'],','.join('0x'+i['score'][k:k+2] for k in range(0,8,2)),i['rescued'],
            f['hud'],f['c2e7'],f['f001'],f['f003'],f['mvs'],f['fd91'],f['c2e6'],f['c303'],f['e9e3'],f['c300'],g['c303'],g['e9e3'],g['c300'],g['f003'],i['timer1']))
        words+=i['fix0']+i['fix1']
        for s in i['steps']:steps.append(s)
out.parent.mkdir(parents=True,exist_ok=True)
with open(out,'w') as o:
    o.write('/* Generated by tools/compile_hud_fixture.py from %s. */\n'%src.name)
    o.write('#define HUD_ROW_COUNT %d\nstatic const unsigned char hud_rows[]={%s};\n'%(len(d['rows']),','.join(map(str,d['rows']))))
    o.write('static const char *const hud_capture_names[]={%s};\n'%','.join('"%s"'%n for n in names))
    o.write('typedef struct {unsigned capture,frozen,f0,f1,words,steps;unsigned short panel[2][13];unsigned char blink[2];unsigned short timer,video,video1;unsigned char score[4];unsigned short rescued;unsigned char flags[10],flags0[4];unsigned short timer1;} hud_interval_t;\n')
    o.write('#define HUD_INTERVALS %d\nstatic const hud_interval_t hud_intervals[]={\n%s};\n'%(len(iv),',\n'.join(iv)))
    o.write('static const unsigned short hud_words[]={%s};\n'%','.join(map(str,words)))
    o.write('/* weapon block (20 bytes), P1 slot (36), input word (4), P1 +15 (1), 10000E (2), 1013DE (2), 10C46A (4), 10C5FC (2), P1 routine (4), P1 +5F (1) */\n')
    o.write('static const char *const hud_steps[]={\n%s};\n'%',\n'.join('"%s"'%s for s in steps))
print(len(iv),'intervals',len(steps),'steps ->',out)
