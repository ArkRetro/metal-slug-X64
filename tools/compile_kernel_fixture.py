#!/usr/bin/env python3
"""Compile data/soldier_kernel_fixture.json.gz into build/kernel_fixture.h."""
import gzip,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
src=Path(sys.argv[1]) if len(sys.argv)>1 else ROOT/'data/soldier_kernel_fixture.json.gz'
with gzip.open(src,'rt') as f:d=json.load(f)
L=['/* Generated by tools/compile_kernel_fixture.py; do not edit. */','#include "../src/neo_kernel.h"',
   'typedef struct { neo_kreq_t q; neo_kobj_t scene; uint16_t w4018,w4068; neo_kres_t r; uint32_t frame,actor,caller; } kernel_case_t;',
   'typedef struct { int32_t x,y; uint8_t parent,b4008,b400a,b400d; int32_t depth; uint16_t w4018,w4068; neo_kobj_t scene; neo_kfloor_t r; uint32_t frame,actor; } floor_case_t;',
   'static const uint8_t kernel_group_map[8]={'+','.join(map(str,d['group_map']))+'};','static const kernel_case_t kernel_cases[]={']
S=d['sweep_columns']
for row in d['sweeps']:
    c=dict(zip(S,row))
    L.append('  {{%(x)d,%(y)d,%(dx)d,%(dy)d,%(parent)d,0x%(mode4004)xu,%(b4008)d,%(b4009)d,%(b400a)d,%(b400b)d,%(b400d)d},'
        '{%(scene_x)d,%(scene_y)d,%(scene_prev_x)d,%(scene_prev_y)d},0x%(w4018)x,0x%(w4068)x,'
        '{%(out_x)d,%(out_y)d,%(out_vx)d,%(out_vy)d,%(out_parent)d,0x%(out_flags)x,0x%(out_kind)xu,0x%(out_w4068)x},%(frame)d,0x%(actor)x,0x%(caller)x},'%c)
L.append('};')
L.append('static const floor_case_t floor_cases[]={')
F=d['floor_columns']
for row in d['floors']:
    c=dict(zip(F,row))
    L.append('  {%(x)d,%(y)d,%(parent)d,%(b4008)d,%(b400a)d,%(b400d)d,%(depth)d,0x%(w4018)x,0x%(w4068)x,{%(scene_x)d,%(scene_y)d,%(scene_prev_x)d,%(scene_prev_y)d},'
        '{%(out_x)d,%(out_y)d,%(out_parent)d,0x%(out_kind)xu,%(out_d6)d,true},%(frame)d,0x%(actor)x},'%c)
L.append('};')
(ROOT/'build').mkdir(exist_ok=True);(ROOT/'build/kernel_fixture.h').write_text('\n'.join(L)+'\n')
