#!/usr/bin/env python3
"""Compile data/soldier_kernel_fixture.json.gz into build/kernel_fixture.h."""
import gzip,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
src=Path(sys.argv[1]) if len(sys.argv)>1 else ROOT/'data/soldier_kernel_fixture.json.gz'
with gzip.open(src,'rt') as f:d=json.load(f)
L=['/* Generated by tools/compile_kernel_fixture.py; do not edit. */','#include "../src/neo_kernel.h"',
   '/* Dynamic collision objects 6/7 at entry: parent, position, cell map (ROM), countdown, box; bins; A6 (+6A, +28). */',
   'typedef struct { struct { uint32_t parent; neo_kobj_t pos; uint32_t map; uint16_t countdown; int32_t bbox[4]; } slot[2]; uint8_t bins_x[18],bins_y[16],solid,self_dyn; uint32_t self_block; } kernel_dyn_t;',
   'typedef struct { neo_kreq_t q; neo_kobj_t scene; uint16_t w4018,w4068; neo_kres_t r; uint32_t frame,actor,caller; int16_t dyn; } kernel_case_t;',
   'typedef struct { int32_t x,y; uint8_t parent,b4008,b400a,b400d; int32_t depth; uint16_t w4018,w4068; neo_kobj_t scene; neo_kfloor_t r; uint32_t frame,actor; int16_t dyn; } floor_case_t;',
   'static const uint8_t kernel_group_map[8]={'+','.join(map(str,d['group_map']))+'};','static const kernel_case_t kernel_cases[]={']
DYN=[]
def s32(v):return v-(1<<32) if v&0x80000000 else v
def dyn_index(dy):
    if not dy:return -1
    slots=[]
    for sl in dy['slots']:
        _,parent,x,y,px,py,m,cd,b0,b1,b2,b3=sl
        slots.append('{0x%x,{%d,%d,%d,%d},0x%x,%d,{%d,%d,%d,%d}}'%(parent,s32(x),s32(y),s32(px),s32(py),m,cd,s32(b0),s32(b1),s32(b2),s32(b3)))
    bx=b''.join(v.to_bytes(4,'big') for v in dy['bins_x'][:4])+dy['bins_x'][4].to_bytes(2,'big')
    by=b''.join(v.to_bytes(4,'big') for v in dy['bins_y'])
    sd,sb=dy['self']
    DYN.append('{{%s},{%s},{%s},%d,%d,0x%x}'%(','.join(slots),','.join(map(str,bx)),','.join(map(str,by)),dy['solid'],0 if sd==0xff else sd+1,sb))
    return len(DYN)-1
S=d['sweep_columns']
for row in d['sweeps']:
    c=dict(zip(S,row));c['dyn']=dyn_index(c.get('dynamic'))
    L.append('  {{%(x)d,%(y)d,%(dx)d,%(dy)d,%(parent)d,0x%(mode4004)xu,%(b4008)d,%(b4009)d,%(b400a)d,%(b400b)d,%(b400d)d},'
        '{%(scene_x)d,%(scene_y)d,%(scene_prev_x)d,%(scene_prev_y)d},0x%(w4018)x,0x%(w4068)x,'
        '{%(out_x)d,%(out_y)d,%(out_vx)d,%(out_vy)d,%(out_parent)d,0x%(out_flags)x,0x%(out_kind)xu,0x%(out_w4068)x},%(frame)d,0x%(actor)x,0x%(caller)x,%(dyn)d},'%c)
L.append('};')
L.append('static const floor_case_t floor_cases[]={')
F=d['floor_columns']
for row in d['floors']:
    c=dict(zip(F,row));c['dyn']=dyn_index(c.get('dynamic'))
    L.append('  {%(x)d,%(y)d,%(parent)d,%(b4008)d,%(b400a)d,%(b400d)d,%(depth)d,0x%(w4018)x,0x%(w4068)x,{%(scene_x)d,%(scene_y)d,%(scene_prev_x)d,%(scene_prev_y)d},'
        '{%(out_x)d,%(out_y)d,%(out_parent)d,0x%(out_kind)xu,%(out_d6)d,true},%(frame)d,0x%(actor)x,%(dyn)d},'%c)
L.append('};')
L.append('static const kernel_dyn_t kernel_dyns[]={'+(','.join(DYN) if DYN else '{0}')+'};')
(ROOT/'build').mkdir(exist_ok=True);(ROOT/'build/kernel_fixture.h').write_text('\n'.join(L)+'\n')
