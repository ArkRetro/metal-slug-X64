#!/usr/bin/env python3
"""data/legs_fixture.json -> build/legs_fixture.h (tools/test_marco_legs.c)."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
d=json.load(open(ROOT/'data/legs_fixture.json'))
cases=[];steps=[]
for c in d['cases']:
    cases.append('{"%s",%d,%d,%d,%d}'%(c['name'],c['moving'],c['jump'],len(steps),len(c['steps'])))
    steps+=['{%d,0x%x,%d,0x%x,%d,0x%x}'%tuple(s) for s in c['steps']]
out=ROOT/'build/legs_fixture.h';out.parent.mkdir(parents=True,exist_ok=True)
out.write_text('/* Generated by tools/compile_legs_fixture.py (%s). */\ntypedef struct {const char *name;int moving,jump;unsigned first,count;} legs_case_t;\ntypedef struct {unsigned frame,cursor,f78,f72,ground,descriptor;} legs_step_t;\n#define LEGS_CASES %d\nstatic const legs_case_t legs_cases[]={%s};\nstatic const legs_step_t legs_steps[]={%s};\n'%(d['source'],len(cases),',\n'.join(cases),',\n'.join(steps)))
print(len(cases),'cases',len(steps),'steps ->',out)
