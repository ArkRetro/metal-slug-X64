#!/usr/bin/env python3
"""data/lspc_fixture.json -> C header for tools/test_neo_lspc.c."""
import json,sys
d=json.load(open(sys.argv[1]));L=['/* generated by tools/compile_lspc_fixture.py */']
for i,r in enumerate(d['runs']):
    L.append('static const uint32_t lspc_w%d[][2]={%s};'%(i,','.join('{%d,%d}'%tuple(x) for x in r['writes']) or '{0xffffffffu,0}'))
    L.append('static const uint32_t lspc_s%d[][2]={%s};'%(i,','.join('{%d,%d}'%tuple(x) for x in r['samples'])))
L.append('static const struct {uint32_t first,last,start_d0;const uint32_t (*w)[2];unsigned nw;const uint32_t (*s)[2];unsigned ns;} lspc_runs[]={%s};'%','.join(
    '{%d,%d,%d,lspc_w%d,%d,lspc_s%d,%d}'%(r['first'],r['last'],r['start_d0'],i,len(r['writes']),i,len(r['samples'])) for i,r in enumerate(d['runs'])))
open(sys.argv[2],'w').write('\n'.join(L)+'\n')
