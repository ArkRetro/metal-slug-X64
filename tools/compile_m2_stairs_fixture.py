#!/usr/bin/env python3
"""Compile data/m2_stairs_fixture.json.gz into build/m2_stairs_fixture.h
(tools/test_m2_stairs.c; docs/MISION2.md, "Fase 2i")."""
import gzip,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
src=Path(sys.argv[1]) if len(sys.argv)>1 else ROOT/'data/m2_stairs_fixture.json.gz'
out=Path(sys.argv[2]) if len(sys.argv)>2 else ROOT/'build/m2_stairs_fixture.h'
with gzip.open(src,'rt') as f:d=json.load(f)
def s32(v):return v-(1<<32) if v&0x80000000 else v
g=d['grid'];cells=bytes.fromhex(g['cells_hex'])
L=['/* Generated by tools/compile_m2_stairs_fixture.py; do not edit. */','#include <stdint.h>',
   'enum { STAIRS_COLUMNS=%d, STAIRS_ROWS=%d, STAIRS_C0=%d, STAIRS_C1=%d, STAIRS_R0=%d, STAIRS_R1=%d };'%(g['columns'],g['rows'],*g['window_columns'],*g['window_rows']),
   'static const uint8_t stairs_window[]={'+','.join(map(str,cells))+'};',
   'static const uint8_t stairs_group_map[8]={'+','.join(map(str,d['group_map']))+'};',
   'typedef struct { int32_t terrain[4],root[4]; uint32_t in[14]; uint32_t out[8]; uint32_t frame; } stairs_sweep_t;',
   'static const stairs_sweep_t stairs_sweeps[]={']
for r in d['sweeps']:
    c=dict(zip(d['sweep_columns'],r))
    t=[c[k] for k in ('terrain_x','terrain_y','terrain_prev_x','terrain_prev_y')];o=[c[k] for k in ('root_x','root_y','root_prev_x','root_prev_y')]
    i=[c[k] for k in ('d0','d1','d2','d3','a0','m4004','b4008','b4009','b400a','b400b','b400c','b400d','w4068','w4018')]
    q=[c[k] for k in ('out_d0','out_d1','out_d2','out_d3','out_a0','out_d4','out_d6','out_d7')]
    L.append('  {{%s},{%s},{%s},{%s},%d},'%(','.join(map(str,t)),','.join(map(str,o)),','.join('0x%xu'%v for v in i),','.join('0x%xu'%v for v in q),c['frame']))
L.append('};')
L.append('typedef struct { uint32_t frame; char input[8]; int32_t x,y,vx,vy; uint8_t flags15; int32_t terrain[4],root[4]; } stairs_update_t;')
L.append('typedef struct { const char *name,*plan; int32_t start[6]; const stairs_update_t *updates; unsigned count; } stairs_run_t;')
for n,r in enumerate(d['runs']):
    L.append('static const stairs_update_t stairs_run%d[]={'%n)
    for u in r['updates']:
        c=dict(zip(d['update_columns'],u))
        L.append('  {%d,"%s",%d,%d,%d,%d,0x%x,{%d,%d,%d,%d},{%d,%d,%d,%d}},'%(c['frame'],c['input'],c['x'],c['y'],c['vx'],c['vy'],c['flags15'],
            c['terrain_x'],c['terrain_y'],c['terrain_prev_x'],c['terrain_prev_y'],c['root_x'],c['root_y'],c['root_prev_x'],c['root_prev_y']))
    L.append('};')
L.append('static const stairs_run_t stairs_runs[]={')
for n,r in enumerate(d['runs']):
    L.append('  {"%s","%s",{%s},stairs_run%d,%d},'%(r['name'],r['plan'],','.join(map(str,r['start'])),n,len(r['updates'])))
L.append('};')
out.parent.mkdir(parents=True,exist_ok=True);out.write_text('\n'.join(L)+'\n')
print('%s: %d sweeps, %d runs'%(out,len(d['sweeps']),len(d['runs'])))
