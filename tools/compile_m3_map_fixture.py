#!/usr/bin/env python3
"""data/m3_map_fixture.json.gz (tools/extract_m3_recon.py) -> C header for
tools/test_m3_map.c. With --sweeps also the player sweeps (the separate
target check-m3sweeps); without them the header holds only the sections,
the cell reads, the patches and the train reads (make check)."""
import argparse,gzip,json
ap=argparse.ArgumentParser();ap.add_argument('fixture');ap.add_argument('output');ap.add_argument('--sweeps',help='filesystem/mission3/m3_sweeps.json.gz (tools/extract_m3_recon.py)')
a=ap.parse_args()
d=json.load(gzip.open(a.fixture));o=open(a.output,'w')
o.write('/* Generated by tools/compile_m3_map_fixture.py from %s. */\n'%a.fixture)
o.write('#define M3_SWEEPS %d\n'%(1 if a.sweeps else 0))
o.write('static const struct {const char *id,*name,*map;uint32_t f0,f1;int32_t cam0,cam1;} m3_sections[]={%s};\n'%','.join(
    '{"%s","%s","%s",%d,%d,%d,%d}'%(s['id'],s['name'],s['map'],s['frames'][0],s['frames'][1],s['camera'][0],s['camera'][1]) for s in d['sections']))
o.write('static const struct {int16_t c,r;uint8_t v,player;uint32_t f0,f1;} m3_terrain[]={\n%s};\n'%',\n'.join(
    '{%d,%d,%d,%d,%d,%d}'%(c,r,v,p,f0,f1) for c,r,v,f0,f1,p in d['terrain']))
o.write('static const struct {int16_t c,q;uint8_t v;uint32_t f0,f1;} m3_train[]={\n%s};\n'%',\n'.join(
    '{%d,%d,%d,%d,%d}'%tuple(t) for t in d['train']))
cells=[];rows=[]
for p in d['patches']:
    rows.append('{%d,0x%sU,{%s},%d,%d}'%(p['frame'],p['submap'],','.join(str(x) for x in p['d']),len(cells),len(p['cells'])))
    cells+=p['cells']
o.write('static const struct {int16_t c,r;uint8_t v;} m3_patch_cells[]={%s};\n'%','.join('{%d,%d,%d}'%tuple(c) for c in cells))
o.write('static const struct {uint32_t frame,submap;uint16_t d[6];uint16_t first,count;} m3_patches[]={\n%s};\n'%',\n'.join(rows))
if a.sweeps:
    d=json.load(gzip.open(a.sweeps))
    maps=d['dynamic_maps'];names=sorted(maps)
    o.write('static const uint8_t m3_map_bytes[]={%s};\n'%','.join(str(b) for n in names for b in bytes.fromhex(maps[n])))
    at=0;idx=[]
    for n in names:idx.append('{0x%sU,%d}'%(n,at));at+=len(bytes.fromhex(maps[n]))
    o.write('static const struct {uint32_t rom,at;} m3_maps[]={%s};\n'%','.join(idx))
    out=[]
    for s in d['sweeps']:
        dyn=','.join('{0x%X,0x%X,0x%X,0x%X,0x%X}'%tuple(x) for x in s['dyn'])
        out.append('{%d,%d,%d,{%s},{%s},0x%X,{%s},%d,0x%X,{%s},{%s}}'%(s['frame'],s['count'],s['section'],','.join('0x%X'%v for v in s['in']),
            ','.join('0x%X'%v for v in s['box']),s['shake'],','.join('0x%X'%v for v in s['scene']),s['origin'] if s['origin']<0x8000 else s['origin']-0x10000,
            s['train_map'],dyn,','.join('0x%X'%v for v in s['out'])))
    o.write('static const struct {uint32_t frame,count;uint8_t section;uint32_t in[14];uint16_t box[4];uint32_t shake,scene[12];int16_t origin;uint32_t train_map,dyn[8][5],out[8];} m3_sweeps[]={\n%s};\n'%',\n'.join(out))
