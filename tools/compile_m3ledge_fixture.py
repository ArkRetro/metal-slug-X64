#!/usr/bin/env python3
"""Compile data/m3ledge_fixture.json into build/m3ledge_fixture.h (the MAME
writes of the wagon ledge stamper 0B8FA8, docs/MISION3.md)."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
d=json.loads((ROOT/'data/m3ledge_fixture.json').read_text())
L=['/* Generated by tools/compile_m3ledge_fixture.py; do not edit. */','#include <stdint.h>',
   'typedef struct { uint16_t column; uint8_t row,value; } m3ledge_cell_t;',
   'enum { M3LEDGE_STEPS=%d, M3LEDGE_CELLS=%d };'%(len(d['steps']),len(d['steps'][0]['cells']))]
assert all(len(s['cells'])==len(d['steps'][0]['cells']) for s in d['steps'])
L.append('static const m3ledge_cell_t m3ledge_steps[M3LEDGE_STEPS][M3LEDGE_CELLS]={'+','.join('{'+','.join('{%d,%d,%d}'%tuple(c) for c in s['cells'])+'}' for s in d['steps'])+'};')
(ROOT/'build').mkdir(exist_ok=True);(ROOT/'build/m3ledge_fixture.h').write_text('\n'.join(L)+'\n')
