#!/usr/bin/env python3
"""data/m4_map_fixture.json.gz (tools/extract_m4_map_fixture.py) -> C header
for tools/test_m4_map.c (make check)."""
import gzip,json,sys
d=json.load(gzip.open(sys.argv[1]));o=open(sys.argv[2],'w')
o.write('/* Generated by tools/compile_m4_map_fixture.py from %s. */\n#include <stdint.h>\n'%sys.argv[1])
o.write('enum { M4_READS=%d, M4_READS_STATIC=%d, M4_READS_PATCH=%d, M4_READS_STAMP=%d, M4_READS_RING=%d, M4_PATCHES=%d };\n'%(
    d['reads'],d['kinds'].get('static',0),d['kinds'].get('patch',0),d['kinds'].get('stamp 0C88B0',0),d['kinds'].get('ring',0)+d['kinds'].get('ring patch',0),len(d['patches'])))
o.write('static const struct { int16_t x,y; uint8_t v; } m4_static[]={%s};\n'%','.join('{%d,%d,%d}'%tuple(r) for r in d['static']))
o.write('static const struct { uint32_t frame,submap; int16_t d[6]; uint16_t cells_changed; } m4_patches[]={%s};\n'%','.join(
    '{%d,0x%s,{%s},%d}'%(p['frame'],p['submap'],','.join(map(str,p['d'])),p['cells_changed']) for p in d['patches']))
