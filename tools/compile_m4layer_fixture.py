#!/usr/bin/env python3
"""Compile data/m4layer_fixture.json.gz (tools/extract_m4layer_fixture.py) into a C header."""
import gzip,json,sys
d=json.load(gzip.open(sys.argv[1]))
L=['/* Generated by tools/compile_m4layer_fixture.py; do not edit. */',
   'typedef struct { uint32_t frame; uint8_t pulse,has_layer,has_root,has_speed[2]; uint32_t l14,l18,r14,r18,s0,s1; } m4layer_record_t;',
   'static const m4layer_record_t m4layer_records[]={']
for r in d['records']:
    hl=int('l14' in r and 'l18' in r);hr=int('r14' in r and 'r18' in r)
    L.append('{%d,%d,%d,%d,{%d,%d},%du,%du,%du,%du,%du,%du},'%(r['frame'],r['pulse'],hl,hr,int('s0' in r),int('s1' in r),r.get('l14',0),r.get('l18',0),r.get('r14',0),r.get('r18',0),r.get('s0',0),r.get('s1',0)))
L.append('};')
open(sys.argv[2],'w').write('\n'.join(L)+'\n')
