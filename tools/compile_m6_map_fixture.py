#!/usr/bin/env python3
"""data/m6_map_fixture.json.gz (tools/extract_m6_map_fixture.py) -> C header
for tools/test_m6_map.c (make check)."""
import gzip,json,sys
d=json.load(gzip.open(sys.argv[1]));o=open(sys.argv[2],'w')
o.write('/* Generated by tools/compile_m6_map_fixture.py from %s. */\n#include <stdint.h>\ntypedef struct { int16_t x,y; uint8_t v; } m6_cell_t;\n'%sys.argv[1])
for k,s in enumerate(d['stages']):
    o.write('static const m6_cell_t m6_static_%d[]={%s};\n'%(k,','.join('{%d,%d,%d}'%tuple(r) for r in s['static'])))
o.write('static const struct { uint32_t descriptor; const m6_cell_t *cells; unsigned count,reads,reads_static,reads_empty,reads_ring,reads_early,reads_stamp,stamps,stamp_cells,reads_previous,'
        'patches,reads_patch,second_reads,second_static,second_empty,second_ring,second_moved,second_distinct; } m6_stages[]={\n')
for k,s in enumerate(d['stages']):
    q=s['kinds'];z=s.get('second',{});zk=z.get('kinds',{})
    o.write(' {0x%s,m6_static_%d,%s},\n'%(s['descriptor'],k,','.join(str(v) for v in (len(s['static']),s['reads'],q.get('static',0),q.get('empty',0),q.get('ring',0)+q.get('ring patch',0),
        q.get('clear before the load',0),q.get('stamp',0),len(s['stamp_writes']),sum(e['cells'] for e in s['stamp_writes']),q.get('previous stage ring',0),
        len(s['patches']),q.get('patch',0),z.get('reads',0),zk.get('static',0),zk.get('empty',0)+zk.get('clear before the load',0)+zk.get('previous stage ring',0),zk.get('ring',0),zk.get('moved origin',0),z.get('distinct',0)))))
o.write('};\n')
