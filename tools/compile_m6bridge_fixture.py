#!/usr/bin/env python3
"""data/m6bridge_fixture.json.gz -> build/m6bridge_fixture.h (tools/test_m6_bridge.c) and
data/m6order_fixture.json.gz -> build/m6order_fixture.h (tools/test_m6_order.c)."""
import gzip, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
d = json.load(gzip.open(ROOT / 'data/m6bridge_fixture.json.gz'))['updates']
IN = ('e970', 'c706', 'c70a', 'c704', 'c702', 'o32', 'o34', 'o36', 'c70c')
OUT = ('c706', 'e94e', 'o32', 'o34', 'c704', 'c70c')
def v(x): return '-1' if x is None else str(x)
L = ['/* Generated by tools/compile_m6bridge_fixture.py; do not edit. */',
     'typedef struct { int64_t in[%d], out[%d]; } m6bridge_case_t;' % (len(IN), len(OUT)),
     'static const m6bridge_case_t m6bridge_cases[]={']
for r in d:
    L.append('{{%s},{%s}},' % (','.join(v(r['in'][k]) for k in IN), ','.join(v(r['out'][k]) for k in OUT)))
L.append('};')
(ROOT / 'build').mkdir(exist_ok=True)
(ROOT / 'build/m6bridge_fixture.h').write_text('\n'.join(L) + '\n')
# data/m6order_fixture.json.gz -> build/m6order_fixture.h (tools/test_m6_order.c).
o = json.load(gzip.open(ROOT / 'data/m6order_fixture.json.gz'))['updates']
K = ('frame', 'cam', 'step', 'wx', 'w14', 'w36', 'swing', 'drive', 'r36', 'x_before', 'x_after', 'step_value', 'drive_value', 'o36',
     'root_vx', 'root_vy', 'fx', 'fy', 'frac_x', 'frac_y')
L = ['/* Generated by tools/compile_m6bridge_fixture.py; do not edit. */',
     'typedef struct { int64_t v[%d]; uint8_t flags[4]; } m6order_case_t;' % len(K),
     'static const m6order_case_t m6order_cases[]={']
for r in o:
    L.append('{{%s},{%s}},' % (','.join(str(r[k]) for k in K), ','.join(str(x) for x in r['flags'])))
L.append('};')
(ROOT / 'build/m6order_fixture.h').write_text('\n'.join(L) + '\n')
# data/m6ring_fixture.json.gz -> build/m6ring_fixture.h (tools/test_m6_ring.c).
g = json.load(gzip.open(ROOT / 'data/m6ring_fixture.json.gz'))
L = ['/* Generated by tools/compile_m6bridge_fixture.py; do not edit. */',
     'static const uint32_t m6ring_clear=%d;' % g['clear'],
     'typedef struct { uint32_t frame; int32_t x, y; int16_t o32, o34; uint8_t b82; uint32_t map; } m6ring_frame_t;',
     'static const m6ring_frame_t m6ring_frames[]={']
L += ['{%d,%d,%d,%d,%d,%d,0x%X},' % tuple(f) for f in g['frames']]
L += ['};', 'typedef struct { uint32_t frame; uint16_t first, count; } m6ring_load_t;', 'static const uint32_t m6ring_bytes[]={']
loads = []; n = 0
for f, w in g['writes']:
    loads.append((f, n, len(w))); n += len(w)
    L.append(','.join('%d' % (o << 8 | v) for o, v in w) + ',')
L += ['};', 'static const m6ring_load_t m6ring_loads[]={'] + ['{%d,%d,%d},' % l for l in loads] + ['};']
L += ['typedef struct { uint16_t offset; uint8_t value; uint32_t first, last; } m6ring_read_t;', 'static const m6ring_read_t m6ring_reads[]={']
L += ['{%d,%d,%d,%d},' % tuple(r[:4]) for r in g['reads']]
order = sorted(range(len(g['reads'])), key=lambda i: g['reads'][i][3])
L += ['};', 'static const uint32_t m6ring_by_last[]={' + ','.join(map(str, order)) + '};', 'static const uint32_t m6ring_read_total=%d;' % sum(r[4] for r in g['reads'])]
(ROOT / 'build/m6ring_fixture.h').write_text('\n'.join(L) + '\n')
