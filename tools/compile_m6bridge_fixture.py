#!/usr/bin/env python3
"""data/m6bridge_fixture.json.gz -> build/m6bridge_fixture.h (tools/test_m6_bridge.c)."""
import gzip, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
d = json.load(gzip.open(ROOT / 'data/m6bridge_fixture.json.gz'))['updates']
IN = ('e970', 'c706', 'c70a', 'c704', 'c702', 'o32', 'o34', 'o36', 'c70c')
OUT = ('c706', 'e94e', 'o32', 'o34', 'c704', 'c70c')
def v(x): return '-1' if x is None else str(x)
L = ['/* Generated by tools/compile_m6bridge_fixture.py; do not edit. */',
     'typedef struct { int64_t in[%d], out[%d]; } m6bridge_case_t;' % (len(IN), len(OUT)),
     'static const m6bridge_case_t m6bridge_cases[]={']
for r in d:
    L.append('{{%s},{%s}},' % (','.join(v(r['in'][k]) for k in IN), ','.join(v(r['out'][k]) for k in OUT)))
L.append('};')
(ROOT / 'build').mkdir(exist_ok=True)
(ROOT / 'build/m6bridge_fixture.h').write_text('\n'.join(L) + '\n')
