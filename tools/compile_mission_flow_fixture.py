#!/usr/bin/env python3
"""Compile data/mission_flow_fixture.json into build/mission_flow_fixture.h."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
d=json.loads((ROOT/'data/mission_flow_fixture.json').read_text())
L=['/* Generated by tools/compile_mission_flow_fixture.py; do not edit. */',
   'typedef struct { uint32_t frame,routine,previous; uint8_t has_ram; uint16_t mission,stage,index,record_index; uint8_t end; uint32_t record; uint8_t cleared[6]; } mission_flow_event_t;',
   'static const mission_flow_event_t mission_flow_events[]={']
for e in d['events']:
    r=e.get('ram')
    if r:L.append('  {%d,0x%X,0x%X,1,%d,%d,%d,%d,%d,0x%X,{%s}},'%(e['frame'],e['routine'],e['previous'],r['mission'],r['stage'],r['index'],r['record_index'],r['end'],r['record'],','.join(str(b) for b in bytes.fromhex(r['cleared']))))
    else:L.append('  {%d,0x%X,0x%X,0,0,0,0,0,0,0,{0}},'%(e['frame'],e['routine'],e['previous']))
L.append('};')
(ROOT/'build').mkdir(exist_ok=True);(ROOT/'build/mission_flow_fixture.h').write_text('\n'.join(L)+'\n')
