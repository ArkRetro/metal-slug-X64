#!/usr/bin/env python3
"""Compile data/mount_fixture.json.gz (player 1's node 1014C4 in the weapons
family traces camelfam/tankfam: the updates that mount, ride and leave a
vehicle) into build/mount_fixture.h for tools/test_marco_mount.c."""
import gzip,json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
def main():
    d=json.load(gzip.open(ROOT/'data/mount_fixture.json.gz'))
    lines=['/* generated by tools/compile_mount_fixture.py */']
    ins=[];outs=[];rows=[]
    for u in d['updates']:
        i0=len(ins)
        for a,v in u['ram_in'].items():ins.append((int(a,16),v))
        o0=len(outs)
        for a,v in u['ram_out']:outs.append((a,v))
        rows.append('{%d,%d,0x%xu,"%s","%s",%d,%d,%d,%d}'%(0 if u['source']=='camelfam' else 1,u['frame'],u['routine'],u['pre'],u['post'],i0,len(ins)-i0,o0,len(outs)-o0))
    lines.append('static const mount_ram_t mount_in[]={%s};'%','.join('{0x%xu,%d}'%x for x in ins))
    lines.append('static const mount_ram_t mount_out[]={%s};'%','.join('{0x%xu,%d}'%x for x in outs))
    lines.append('static const mount_update_t mount_updates[]={\n%s};'%',\n'.join(rows))
    (ROOT/'build').mkdir(exist_ok=True);(ROOT/'build/mount_fixture.h').write_text('\n'.join(lines)+'\n')
    print(len(rows),'updates',len(ins),'reads',len(outs),'writes')
if __name__=='__main__':main()
