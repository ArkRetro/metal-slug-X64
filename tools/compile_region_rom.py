#!/usr/bin/env python3
"""Compile data/region_rom.json into build/region_rom.h (rom_data lookup)."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
d=json.loads((ROOT/'data/region_rom.json').read_text())
L=['/* Generated by tools/compile_region_rom.py; do not edit. */','#ifndef REGION_ROM_H','#define REGION_ROM_H','#include <stddef.h>','#include <stdint.h>']
# A blob of a mission group ("m2" .. "m5": read only by that mission's actors) is
# left out of the console image: the mission pack serves it (pack_mission.py
# 'MSXD', scene_stage_rom; docs/MEMORY_OPTIMIZATION.md rule 5).
GUARD={'m2':'!defined(N64)','m3':'!defined(N64)','m4':'!defined(N64)','m5':'!defined(N64)','m6':'!defined(N64)'}
# The SV-001's pose tables and records (51.6 KB, read only by neo_tank.c through 2- and 1-byte ROM reads) stay in the
# cartridge on the console: build/romblobs.bin ('MSXB', version 1, count, data bytes; then the bytes), each read by DMA
# into a small window (program_file_rom, docs/RENDIMIENTO.md "Bloques de ROM en el cartucho"). Host: in the image.
CART=(0x291cea,0x2b0386)
for b in d['blobs']:
    if int(b['rom'],16) in CART:b['group']='cart'
GUARD['cart']='!defined(N64)'
cart=[b for b in d['blobs'] if b.get('group')=='cart'];blob=bytearray();cart_at=[]
for b in cart:cart_at.append(len(blob));blob+=bytes.fromhex(b['hex']);blob+=b'\0'*(len(blob)&1)
import struct
(ROOT/'build').mkdir(exist_ok=True);(ROOT/'build/romblobs.bin').write_bytes(b'MSXB'+struct.pack('>HHII',1,len(cart),len(blob),0)+bytes(blob))
for i,b in enumerate(d['blobs']):
    data=bytes.fromhex(b['hex'])
    g=b.get('group')
    if g:L.append('#if %s'%GUARD[g])
    L.append('static const uint8_t region_blob_%d[]={%s}; /* %s */'%(i,','.join(str(x) for x in data),b['reader']))
    if g:L.append('#endif')
L.append('typedef struct { uint32_t address; uint16_t length; const uint8_t *data; } region_blob_t;')
L.append('static const region_blob_t region_blobs[]={')
for i,b in enumerate(d['blobs']):
    g=b.get('group')
    if g:L.append('#if %s'%GUARD[g])
    L.append('{%s,%d,region_blob_%d},'%(b['rom'],len(b['hex'])//2,i))
    if g:L.append('#endif')
L.append('};')
L.append('#if defined(N64)')
L.append('typedef struct { uint32_t address,length,offset; } region_cart_t;   /* offset: in /romblobs.bin after its 16-byte head */')
L.append('static const region_cart_t region_cart[]={%s};'%','.join('{%s,%d,%d}'%(b['rom'],len(b['hex'])//2,o) for b,o in zip(cart,cart_at)))
L.append('#endif')
L.append('#endif')
(ROOT/'build').mkdir(exist_ok=True);(ROOT/'build/region_rom.h').write_text('\n'.join(L)+'\n')
