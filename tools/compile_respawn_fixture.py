#!/usr/bin/env python3
"""data/respawn_fixture.json -> build/respawn_fixture.h (tools/test_marco_death.c)."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
d=json.load(open(ROOT/'data/respawn_fixture.json'))
out=ROOT/'build/respawn_fixture.h';out.parent.mkdir(parents=True,exist_ok=True)
cases=[];qs=[]
for c in d['cases']:
    cases.append('{%d,%d,0x%x,0x%xu,0x%xu,0x%xu,0x%xu,%d,%d,0x%xu,%d}'%(c['frame'],c['progress'],c['record'],c['x'],c['y'],c['root_x'],c['root_y'],
                 len(qs),len(c['queries']),c['placed_x'],c['type']))
    for q in c['queries']:qs.append('{%d,0x%xu,0x%xu,0x%xu,0x%xu,%d,0x%xu}'%tuple(q))
t=bytes.fromhex(d['table_hex'])
with open(out,'w') as o:
    o.write('/* Generated by tools/compile_respawn_fixture.py (%s). */\n'%d['source'])
    o.write('typedef struct {unsigned frame,progress,record;unsigned x,y,root_x,root_y;unsigned first,count;unsigned placed_x,type;} respawn_case_t;\n')
    o.write('typedef struct {unsigned side;unsigned x28,px,py,limit;unsigned carry;unsigned d6;} respawn_query_t;\n')
    o.write('#define RESPAWN_TABLE_ROM %s\nstatic const unsigned char respawn_table[]={%s};\n'%(d['table'],','.join(str(b) for b in t)))
    o.write('#define RESPAWNS %d\nstatic const respawn_case_t respawn_cases[]={%s};\n'%(len(cases),',\n'.join(cases)))
    o.write('static const respawn_query_t respawn_queries[]={%s};\n'%',\n'.join(qs or ['{0}']))
print(len(cases),'respawns',len(qs),'queries ->',out)
