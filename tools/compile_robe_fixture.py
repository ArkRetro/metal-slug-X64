#!/usr/bin/env python3
"""Compile data/robe_fixture.json.gz (tools/extract_rest_family.py) into build/robe_fixture.h."""
import gzip,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
d=json.load(gzip.open(ROOT/'data/robe_fixture.json.gz','rt'))
L=['/* Generated by tools/compile_robe_fixture.py; do not edit. */','#ifndef ROBE_FIXTURE_H','#define ROBE_FIXTURE_H','#include <stdint.h>',
   'typedef struct { uint32_t frame,routine; uint8_t pre[0xb0],post[0xb0]; int32_t root_x,root_y; int32_t progress,p1x,epoch,groups6; uint8_t write606,value606; } robe_update_t;',
   'static const robe_update_t robe_updates[]={']
def rd(u,a):
    v=u['reads'].get(hex(a))
    if v is None:return None
    mask,data=v
    return (data>>8)&255 if mask==0xff00 else data&255 if mask==0xff else data
last=dict(rx=None,ry=None,pr=-1,p1=-1,ep=-1,g6=-1)
for u in d['updates']:
    x0,x1,y0,y1=(rd(u,a) for a in (0x10e97c,0x10e97e,0x10e980,0x10e982))
    rx=(x0<<16|x1) if x0 is not None and x1 is not None else last['rx']
    ry=(y0<<16|y1) if y0 is not None and y1 is not None else last['ry']
    if rx is not None and rx>=1<<31:rx-=1<<32
    if ry is not None and ry>=1<<31:ry-=1<<32
    pr=rd(u,0x10e99e);p1=rd(u,0x101500);ep=rd(u,0x10c33a);g6=rd(u,0x10c32c)
    last.update(rx=rx,ry=ry)
    w=[x for x in u['writes606']];wv=0
    if w:
        addr,mask,data=w[0];wv=(data>>8)&255 if mask==0xff00 else data&255
    def b(h):return ','.join(str(x) for x in bytes.fromhex(h))
    L.append('{%d,0x%x,{%s},{%s},%d,%d,%d,%d,%d,%d,%d,%d},'%(u['frame'],u['routine'],b(u['pre']),b(u['post']),rx if rx is not None else 0,ry if ry is not None else 0,
        pr if pr is not None else -1,p1 if p1 is not None else -1,ep if ep is not None else -1,g6 if g6 is not None else -1,1 if w else 0,wv))
L+=['};','#endif']
(ROOT/'build').mkdir(exist_ok=True);(ROOT/'build/robe_fixture.h').write_text('\n'.join(L)+'\n')
print(len(d['updates']),'robe updates')
