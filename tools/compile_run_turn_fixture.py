#!/usr/bin/env python3
"""data/run_turn_fixture.json -> build/run_turn_fixture.h (B84,
tools/test_marco_visual.c)."""
import json
from pathlib import Path
R=Path(__file__).resolve().parents[1]
d=json.loads((R/'data/run_turn_fixture.json').read_text())
o=['/* Generated by tools/compile_run_turn_fixture.py from data/run_turn_fixture.json. */',
   'typedef struct {uint16_t frame;uint8_t moving,aim_up,pressed,lost,fired;int8_t facing,hgun;uint8_t count;uint32_t draw[4];uint8_t flip[4];} run_turn_row_t;',
   'typedef struct {const char *capture;uint8_t form,cgun;uint16_t rows;} run_turn_segment_t;',
   'static const run_turn_segment_t run_turn_segments[]={'+','.join('{"%s",%d,%d,%d}'%(s['capture'],s['form'],s['cgun'],len(s['rows'])) for s in d['segments'])+'};',
   'static const run_turn_row_t run_turn_rows[]={']
for s in d['segments']:
    for r in s['rows']:
        assert len(r['draws'])<=4
        dr=[x[0] for x in r['draws']]+[0]*(4-len(r['draws']));fl=[x[1] for x in r['draws']]+[0]*(4-len(r['draws']))
        o.append('{%d,%d,%d,%d,%d,%d,%d,%d,%d,{%s},{%s}},'%(r['frame'],r['moving'],r['aim_up'],r['pressed'],r.get('lost',False),r['fired'],r['facing'],r['hgun'],len(r['draws']),
            ','.join('0x%06X'%x for x in dr),','.join(map(str,fl))))
o.append('};')
(R/'build/run_turn_fixture.h').write_text('\n'.join(o)+'\n')
