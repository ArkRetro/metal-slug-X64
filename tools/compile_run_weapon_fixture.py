#!/usr/bin/env python3
"""data/run_weapon_fixture.json -> build/run_weapon_fixture.h (B83,
tools/test_marco_visual.c)."""
import json
from pathlib import Path
R=Path(__file__).resolve().parents[1]
d=json.loads((R/'data/run_weapon_fixture.json').read_text())
o=['/* Generated by tools/compile_run_weapon_fixture.py from data/run_weapon_fixture.json. */',
   'typedef struct {uint16_t frame;uint8_t moving,fired;int8_t facing;uint8_t count;uint32_t draw[4];uint8_t flip[4];} run_weapon_row_t;',
   'static const uint16_t run_weapon_segments[]={'+','.join(str(len(s)) for s in d['segments'])+'};',
   'static const run_weapon_row_t run_weapon_rows[]={']
for s in d['segments']:
    for r in s:
        assert len(r['draws'])<=4
        dr=[x[0] for x in r['draws']]+[0]*(4-len(r['draws']));fl=[x[1] for x in r['draws']]+[0]*(4-len(r['draws']))
        o.append('{%d,%d,%d,%d,%d,{%s},{%s}},'%(r['frame'],r['moving'],r['fired'],r['facing'],len(r['draws']),','.join('0x%06X'%x for x in dr),','.join(map(str,fl))))
o.append('};')
(R/'build/run_weapon_fixture.h').write_text('\n'.join(o)+'\n')
