#!/usr/bin/env python3
"""Compile data/soldier_script_fixture.json.gz into build/soldier_script_fixture.h."""
import gzip,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
src=Path(sys.argv[1]) if len(sys.argv)>1 else ROOT/'data/soldier_script_fixture.json.gz'
with gzip.open(src,'rt') as f:d=json.load(f)
SCRIPT=0x101414
F=['routine','flags15','flash','field18','word1e','anim','timer','speed','x','y','vx','vy','parent','px','py','cx','cy',
   'mark','correction','health','field50','timer5a','f5b','f5c','f5d','f5e','flags5f','scalar62','field66','variant68','group69','kind_angle']
def ctor(name,k):
    sc=k['scene'];pl=sc['players']
    return 'static const script_construct_t %s={{%s,{%s}},{%s},%d,%d,{%s},%d,0x%x,%d,%d,%d,%d,%d,%d,%d,{%s}};'%(name,
        ','.join('0x%xu'%(k['after'][f]&0xffffffff) for f in F),','.join(map(str,k['locals'])),
        ','.join(map(str,k['rng']['words'])),k['rng']['cursor'],k['rng']['calls'],
        ','.join(str(s32(v)) for v in sc['terrain']),sc['epoch'],sc['camera'],pl['p1x'],pl['p1y'],pl['p2x'],pl['p2y'],pl['mask'],pl['mode88'],pl['rank'],
        ','.join(map(str,sc['grid'])))
L=['/* Generated by tools/compile_soldier_script.py; do not edit. */','#include <stddef.h>','#include <stdint.h>','#include <stdbool.h>',
   'typedef struct { uint32_t record; uint16_t timer72,count76; } script_runner_t;',
   'typedef struct { uint32_t '+','.join(F)+'; uint8_t locals[38]; } ctor_snapshot_t;',
   'typedef struct { ctor_snapshot_t after; uint16_t rng_words[55]; uint8_t rng_cursor,rng_calls; int32_t terrain[4]; uint8_t epoch; uint16_t camera;',
   '  uint16_t p1x,p1y,p2x,p2y; uint8_t mask,mode88,rank; uint16_t grid[128]; } script_construct_t;',
   'typedef struct { uint32_t creator_record,record; uint8_t group69,variant68; const script_construct_t *construct; } script_spawn_t;',
   'typedef struct { bool alive; uint8_t fx,fy; uint16_t px,py; } script_player_t;',
   'typedef struct { uint32_t frame; uint16_t camera; int32_t scroll_x,scroll_y; script_player_t players[2]; uint8_t groups[9];',
   '  uint8_t rng_count; uint16_t rng[4]; uint32_t pc; uint16_t timer72; uint8_t runner_count; script_runner_t runners[8];',
   '  uint8_t groups_after[9]; int32_t lock; uint8_t spawn_count; script_spawn_t spawns[6]; } script_tick_t;',
   'typedef struct { const char *name; uint32_t pc; uint16_t timer72; uint8_t runner_count; script_runner_t runners[8]; uint16_t w4330,w4332,w69b8,w69ba; int32_t lock; const script_tick_t *ticks; unsigned tick_count; } script_capture_t;']
def s32(v):return v-(1<<32) if v&0x80000000 else v
for i,c in enumerate(d['captures']):
    for j,t in enumerate(c['ticks']):
        for k,sp in enumerate(t['expect']['spawned']):
            if 'construct' in sp:L.append(ctor('script_ctor_%d_%d_%d'%(i,j,k),sp['construct']))
    L.append('static const script_tick_t script_ticks_%d[]={'%i)
    for j,t in enumerate(c['ticks']):
        e=t['expect'];assert len(t['rng'])<=4 and len(e['runners'])<=8 and len(e['spawned'])<=6
        pl=t.get('players') or [dict(alive=t['any_player'],fx=255,fy=255,px=0,py=0),dict(alive=False,fx=0,fy=0,px=0,py=0)]
        lock=e.get('lock',0xffffffff)
        L.append('  {%d,%d,%d,%d,{%s},{%s},%d,{%s},0x%x,%d,%d,{%s},{%s},%d,%d,{%s}},'%(t['frame'],t['camera'],s32(t['scroll_x']),s32(t['scroll_y']),
            ','.join('{%d,%d,%d,%d,%d}'%(1 if p['alive'] else 0,p['fx'],p['fy'],p['px'],p['py']) for p in pl),
            ','.join(map(str,t['groups'])),len(t['rng']),','.join(map(str,t['rng'] or [0])),
            e['pc'],e['timer72'],len(e['runners']),','.join('{0x%x,%d,%d}'%(r['record'],r['timer72'],r['count76']) for r in e['runners']) or '{0}',
            ','.join(map(str,e['groups'])),-1 if lock==0xffffffff else lock>>16,len(e['spawned']),
            ','.join('{0x%x,0x%x,%d,%d,%s}'%(0 if sp['creator_record']==SCRIPT else sp['creator_record'],sp.get('record',0),sp['group69'],sp['variant68'],
                '&script_ctor_%d_%d_%d'%(i,j,k) if 'construct' in sp else 'NULL') for k,sp in enumerate(e['spawned'])) or '{0}'))
    L.append('};')
L.append('static const script_capture_t script_captures[]={'+','.join('{"%s",0x%x,%d,%d,{%s},%d,%d,%d,%d,%d,script_ticks_%d,%d}'%(c['capture'],c['pc'],c['timer72'],len(c['runners']),
    ','.join('{0x%x,%d,%d}'%(r['record'],r['timer72'],r['count76']) for r in c['runners']) or '{0}',c['w4330'],c['w4332'],c.get('w69b8',0x80),c.get('w69ba',0x180),
    -1 if c.get('lock',0xffffffff)==0xffffffff else c['lock']>>16,i,len(c['ticks'])) for i,c in enumerate(d['captures']))+'};')
(ROOT/'build').mkdir(exist_ok=True);(ROOT/'build/soldier_script_fixture.h').write_text('\n'.join(L)+'\n')
print(sum(len(c['ticks']) for c in d['captures']),'script updates')
