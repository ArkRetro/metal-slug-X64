#!/usr/bin/env python3
"""Compile the per-update soldier fixture into build/soldier_tick_fixture.h."""
import gzip,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
src=Path(sys.argv[1]) if len(sys.argv)>1 else ROOT/'data/soldier_tick_fixture.json.gz'
dst=Path(sys.argv[2]) if len(sys.argv)>2 else ROOT/'build/soldier_tick_fixture.h'
with gzip.open(src,'rt') as f:d=json.load(f)
F=['routine','flags15','flash','field18','word1e','anim','timer','speed','x','y','vx','vy','parent','px','py','cx','cy',
   'mark','correction','health','field50','timer5a','f5b','f5c','f5d','f5e','flags5f','scalar62','field66','variant68','group69','kind_angle']
L=['/* Generated by tools/compile_soldier_ticks.py; do not edit. */','#include <stdint.h>','#include <stdbool.h>',
   'typedef struct { uint32_t '+','.join(F)+'; uint8_t locals[38]; } tick_snapshot_t;',
   'typedef struct { bool after_soldier; int32_t x,y,vx,vy; uint32_t parent; int32_t px,py,cx,cy; uint8_t flags15,flags5f,mark,correction,f6f,f5e; uint16_t kind_angle; } tick_bullet_t;',
   'typedef struct { const char *capture; uint32_t frame,node; tick_snapshot_t before,after; bool deleted,has_after;',
   '  uint16_t rng_words[55]; uint8_t rng_cursor,rng_calls; int32_t terrain[4]; uint8_t epoch; uint16_t camera;',
   '  uint16_t p1x,p1y,p2x,p2y; uint8_t mask,mode88,rank; uint16_t grid[128]; uint16_t hx,hy; uint8_t hflags15; uint32_t hdesc; bool hdead,hlive; uint16_t bounds[4]; const tick_bullet_t *bullets; uint8_t bullet_count; bool external_attack; } tick_case_t;',
   ]
def sx(v):return v-(1<<32) if v&0x80000000 else v
for i,c in enumerate(d['cases']):
    if c.get('bullets'):
        L.append('static const tick_bullet_t tick_bullets_%d[]={'%i+','.join('{%d,%d,%d,%d,%d,0x%x,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,0x%x}'%(
            1 if b['after_soldier'] else 0,sx(b['body']['x']),sx(b['body']['y']),sx(b['body']['vx']),sx(b['body']['vy']),b['body']['parent'],
            sx(b['body']['px']),sx(b['body']['py']),sx(b['body']['cx']),sx(b['body']['cy']),b['flags15'],b['flags5f'],b['mark'],b['correction'],
            b['f6f'],b['f5e'],b['kind_angle']) for b in c['bullets'])+'};')
L.append('static const tick_case_t tick_cases[]={')
def snap(s,loc):
    if s is None:return '{0}'
    return '{'+','.join('0x%xu'%(s[k]&0xffffffff) for k in F)+',{'+','.join(map(str,loc or [0]*38))+'}}'
for i,c in enumerate(d['cases']):
    sc=c['scene'];pl=sc['players'];p1=sc['p1']
    bl='tick_bullets_%d,%d'%(i,len(c['bullets'])) if c.get('bullets') else 'NULL,0'
    fmt='  {"%s",%d,0x%x,%s,%s,%d,%d,{%s},%d,%d,{%s},%d,0x%x,%d,%d,%d,%d,%d,%d,%d,{%s},%d,%d,%d,0x%x,%d,%d,{%s},'+bl+','+('1' if c.get('external_attack') else '0')+'},'
    L.append(fmt%(
        c['capture'],c['frame'],c['node'],snap(c['before'],c['locals_before']),snap(c['after'],c['locals_after']),
        1 if c['deleted'] else 0,1 if c['after'] else 0,','.join(map(str,c['rng']['words'])),c['rng']['cursor'],c['rng']['calls'],
        ','.join(str(v-(1<<32) if v&0x80000000 else v) for v in sc['terrain']),sc['epoch'],sc['camera'],
        pl['p1x'],pl['p1y'],pl['p2x'],pl['p2y'],pl['mask'],pl['mode88'],pl['rank'],','.join(map(str,sc['grid'])),
        p1['x'],p1['y'],p1['flags15'],p1['descriptor'],1 if p1['dead'] else 0,1 if p1['live'] else 0,
        ','.join(str(sc['bounds'][k]) for k in ('left','top','right','bottom'))))
    assert not c['scene']['bounds']['parent'],'Bounds parent not modelled in this fixture'
L.append('};')
dst.write_text('\n'.join(L)+'\n')
print(len(d['cases']),'cases')
