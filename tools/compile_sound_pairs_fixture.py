#!/usr/bin/env python3
"""Measured pairs of data/sound_policy.json (tools/measure_sound_pairs.py:
isolated renders of the original Z80 driver, 'A then B' 12 frames apart)
as a C header for tools/test_msx_sfx.c: every pair of two effects with a
clear outcome (cut, drop, overlap). Numbers only. Usage:
compile_sound_pairs_fixture.py [--policy JSON] --output H"""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--policy',type=Path,default=ROOT/'data/sound_policy.json');p.add_argument('--output',type=Path,required=True)
    a=p.parse_args();d=json.loads(a.policy.read_text())['sounds'];word={l:int(s['word'],16) for l,s in d.items()}
    pairs={}
    for s in d.values():
        for k,mode in s['pairs'].items():
            x,y=k.split('>')
            if mode in ('cut','drop','overlap') and x in word and y in word:pairs[(word[x],word[y])]=mode
    L=['/* Generated by tools/compile_sound_pairs_fixture.py from data/sound_policy.json; do not edit. */',
       'static const struct {uint16_t first,second;char outcome;} sound_pairs[]={']
    L+=['    {0x%04x,0x%04x,%r},'%(x,y,m[0]) for (x,y),m in sorted(pairs.items())]
    L+=['};','']
    a.output.parent.mkdir(parents=True,exist_ok=True);a.output.write_text('\n'.join(L).replace("'","'")+'\n')
    print(len(pairs),'pairs ->',a.output)
if __name__=='__main__':main()
