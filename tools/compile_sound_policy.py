#!/usr/bin/env python3
"""Compile the gameplay effects' policy into src/msx_sfx_policy.h with the
rule of the Z80 sound driver (250-m1.m1, docs/AUDIO_JUEGO.md 19,
tools/sound_driver_table.py): each effect's group D, the priority byte E of
its first track and its stop list (the four request words of its header)
come from the driver's effect header (506F), read from the ROM zip:

  - 5204: starting an effect first stops the playing effects whose words are
    in its stop list;
  - 50CF: with D != 0, a playing effect of the same group is stopped and its
    slot reused when its priority byte >= E (equal bytes cut each other, the
    same word restarts), else the new effect is dropped (lower byte = higher
    priority); other groups take another slot.

One output channel per group (D = 0: one per effect). The set of effects is
the one data/sound_policy.json maps (labels of --keep: the words the header
already plays, so the resident set does not change). Numbers only (no
audio). Usage:
compile_sound_policy.py --rom mslugx.zip [--keep src/msx_sfx_policy.h] [--output H]"""
import argparse,json,re,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tools'))
from sound_driver_table import load,effect
def main():
    p=argparse.ArgumentParser(description=__doc__,formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--rom',type=Path,required=True)
    p.add_argument('--policy',type=Path,default=ROOT/'data/sound_policy.json')
    p.add_argument('--keep',type=Path,help='a policy header: only its words (and the base twelve) are emitted')
    p.add_argument('--output',type=Path,default=ROOT/'src/msx_sfx_policy.h')
    a=p.parse_args();m=load(a.rom);d=json.loads(a.policy.read_text())['sounds']
    keep=None
    if a.keep:keep={int(w,16) for w in re.findall(r'\{0x([0-9a-f]{4}),',a.keep.read_text())}
    # The twelve effects of the first measurement (their files' names).
    BASE={0x10f7:'pistol',0x108d:'vehicle_hit',0x1027:'explosion',0x10fa:'knife_hit',0x1023:'vehicle_smoke',0x1033:'vehicle_burst',
          0x103e:'rebel_103e',0x103f:'rebel_103f',0x1040:'rebel_1040',0x1041:'rebel_1041',0x1042:'rebel_1042',0x1043:'rebel_1043'}
    labels=dict(BASE)
    for label,s in d.items():
        w=int(s['word'],16)
        if w in BASE:assert label==BASE[w],(label,BASE[w]);continue
        if label.startswith('sfx_') and (keep is None or w in keep):labels[w]=label
    sounds=[]
    for w,label in labels.items():
        e=effect(m,w)
        sounds.append(dict(word=w,label=label,group=e['group'],priority=e['tracks'][0]['priority'],stops=[int(x,16) for x in e['stops']]))
    sounds.sort(key=lambda s:s['word'])
    groups=sorted({s['group'] for s in sounds if s['group']})
    channel={}
    for g in groups:channel[('g',g)]=len(channel)
    for s in sounds:
        if not s['group']:channel[('w',s['word'])]=len(channel)
    ch=lambda s:channel[('g',s['group'])] if s['group'] else channel[('w',s['word'])]
    stops=sorted({w for s in sounds for w in s['stops']})
    L=['/* Generated by tools/compile_sound_policy.py from the Z80 driver header of each',
       ' * effect (250-m1.m1: group, first track priority, stop list) and the labels of',
       ' * data/sound_policy.json; do not edit. */',
       '#define MSX_SFX_POLICY_CHANNELS %du'%len(channel),
       '#define MSX_SFX_POLICY_COUNT %du'%len(sounds),
       '#define MSX_SFX_POLICY_DEFS \\']
    for s in sounds:
        st=",".join("0x%04x"%w for w in s["stops"]) or "0"
        L.append('    {0x%04x,0x%02x,0x%02x,%u,{%s},"%s"}, \\'%(s['word'],s['group'],s['priority'],ch(s),st,s['label']))
    L.append('')
    a.output.write_text('\n'.join(L)+'\n')
    print(len(sounds),'effects,',len(channel),'channels (',len(groups),'groups ),',sum(1 for s in sounds if s['stops']),'with stop lists')
if __name__=='__main__':main()
