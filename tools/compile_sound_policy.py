#!/usr/bin/env python3
"""Compile data/sound_policy.json (tools/derive_sound_policy.py) into
src/msx_sfx_policy.h: the new effects' request words, driver channels and
levels for src/msx_sfx.c. The twelve effects of the first measurement keep
their hand-written entries; only labels starting with sfx_ are emitted.
Numbers only (no audio)."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
BASE=['weapon','impact','voice']
def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--policy',type=Path,default=ROOT/'data/sound_policy.json')
    p.add_argument('--render',type=Path,default=None,help='render.json: labels whose status is not OK are left out')
    p.add_argument('--output',type=Path,default=ROOT/'src/msx_sfx_policy.h')
    a=p.parse_args();d=json.loads(a.policy.read_text())['sounds']
    ok=None
    if a.render:ok={k for k,v in json.loads(a.render.read_text())['sounds'].items() if v['status']=='OK'}
    new=sorted(l for l in d if l.startswith('sfx_') and (ok is None or l in ok))
    extra=sorted({d[l]['channel'] for l in new}-set(BASE))
    chan={c:'MSX_SFX_CH_%s'%c.upper() for c in BASE+extra}
    L=['/* Generated by tools/compile_sound_policy.py from data/sound_policy.json; do not edit. */',
       '#define MSX_SFX_POLICY_CHANNELS %s'%','.join(chan[c] for c in extra),
       '#define MSX_SFX_POLICY_IDS %s'%','.join('MSX_SFX_W%s'%d[l]['word'].upper() for l in new),
       '#define MSX_SFX_POLICY_DEFS \\']
    for l in new:
        L.append('    [MSX_SFX_W%s]={0x%s,%s,%d,"%s"}, \\'%(d[l]['word'].upper(),d[l]['word'].lower(),chan[d[l]['channel']],d[l]['level'],l))
    L.append('')
    a.output.write_text('\n'.join(L)+'\n')
    print(len(new),'effects,',len(extra),'new channels')
if __name__=='__main__':main()
