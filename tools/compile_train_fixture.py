#!/usr/bin/env python3
"""data/train_fixture.json.gz -> C header for tools/test_neo_train.c."""
import gzip,json,sys
d=json.load(gzip.open(sys.argv[1]));o=open(sys.argv[2],'w')
calls=[];rows=[]
for u in d['updates']:
    first=len(calls)
    for kind,v in u[1]:calls.append((1 if kind=='own' else 0,v))
    rows.append('{%d,%d,%d,%d,%d}'%(u[0],first,len(calls)-first,u[2],u[3]))
o.write('/* Generated by tools/compile_train_fixture.py from %s. */\n'%sys.argv[1])
o.write('static const int32_t train_start_x=%d;static const int16_t train_start_origin=%d;\n'%(d['start_x'],d['start_origin']))
o.write('static const struct {uint8_t own;uint32_t value;} train_calls[]={%s};\n'%','.join('{%d,0x%X}'%c for c in calls))
o.write('static const struct {int32_t root_dx;uint16_t first,count;int32_t x;int16_t origin;} train_updates[]={\n%s};\n'%',\n'.join(rows))
