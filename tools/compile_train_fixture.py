#!/usr/bin/env python3
"""data/train_fixture.json.gz -> C header for tools/test_neo_train.c."""
import gzip,json,sys
d=json.load(gzip.open(sys.argv[1]));o=open(sys.argv[2],'w')
KIND={'call':0,'own':1,'sky_own':2,'sky_factor':3}
calls=[];rows=[];checks=[];ring=[]
for u in d['updates']:
    first=len(calls)
    for kind,v in u[1]:calls.append((KIND[kind],v))
    rows.append('{%d,%d,%d,%d,%d,%d,%d}'%(u[0],first,len(calls)-first,u[2],u[3],u[4],u[5]))
for i,seen in d['rings']:
    checks.append('{%d,%d,%d}'%(i,len(ring),len(seen)));ring.extend('{%d,%d}'%(k,m) for k,m in seen)
o.write('/* Generated by tools/compile_train_fixture.py from %s. */\n'%sys.argv[1])
o.write('static const int32_t train_start_x=%d,train_start_sky=%d;static const int16_t train_start_origin=%d;\n'%(d['start_x'],d['start_sky'],d['start_origin']))
o.write('static const struct {uint8_t kind;uint32_t value;} train_calls[]={%s};\n'%','.join('{%d,0x%X}'%c for c in calls))
o.write('static const struct {int32_t root_dx;uint16_t first,count;int32_t x;int16_t origin;int32_t sky;int16_t o36;} train_updates[]={\n%s};\n'%',\n'.join(rows))
o.write('static const struct {uint16_t update,first,count;} train_ring_checks[]={%s};\n'%',\n'.join(checks))
o.write('static const struct {uint8_t sprite;uint16_t column;} train_ring_columns[]={%s};\n'%','.join(ring))
