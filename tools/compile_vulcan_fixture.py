#!/usr/bin/env python3
"""Compile data/vulcan_fixture.json.gz (tools/extract_vulcan_fixture.py) into
build/vulcan_fixture.h for tools/test_neo_vulcan.c: per turret update the
node bytes before/after and the inputs it read; the aim tables 03B4B0[+72]
from data/region_rom.json."""
import gzip,json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
def main():
    d=json.load(gzip.open(ROOT/'data/vulcan_fixture.json.gz','rt'))
    blobs=[(int(b['rom'],16),bytes.fromhex(b['hex'])) for b in json.load(open(ROOT/'data/region_rom.json'))['blobs']]
    def rom(a,n):
        for b,h in blobs:
            if b<=a and a+n<=b+len(h):return h[a-b:a-b+n]
        raise SystemExit('ROM %06x not in data/region_rom.json'%a)
    L=['/* Generated by tools/compile_vulcan_fixture.py; do not edit. */','#include <stdint.h>']
    L.append('static const uint8_t vulcan_aim[6][64]={%s};'%','.join('{%s}'%','.join(map(str,rom(int.from_bytes(rom(0x3b4b0+4*k,4),'big'),64))) for k in range(6)))
    L.append('static const vulcan_update_t vulcan_updates[]={')
    srcs=[]
    for u in d['updates']:
        i=u['inputs'];pre=bytes.fromhex(u['pre']);post=bytes.fromhex(u['post'])
        ex=i.get('exists',{})
        creator=int.from_bytes(pre[0x0c:0x10],'big')
        alive=not (ex.get('%x'%creator)==0 and ex.get('%x'%(creator+2))==0x3f1e)
        def w(k,default=-1):
            v=i.get(k)
            if v is None:return default
            return (v[2]>>8)&255 if v[1]==0xff00 else v[2]&255 if v[1]==0xff else v[2]
        # 0AAB84 (rider), from what it read: the vehicle node word in slot +00
        # and +1C, player 1's 0040AC (P2 absent in these runs).
        p1=ex.get('1014c4') is None or not (ex.get('1014c4')==0 and ex.get('1014c6')==0x3f1e)
        rider=0 if ('slot0' in i and p1 and w('slot0')==int.from_bytes(pre[0x0e:0x10],'big') and w('slot1c',0)!=0) else -1
        if u['source'] not in srcs:srcs.append(u['source'])
        L.append('{%d,%d,0x%s,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,{%s},{%s}},'%(u['frame'],srcs.index(u['source']),u['node'],int(alive),w('creator5f',0),w('anchor',0),rider,w('new',0),w('held',0),int(w('repeat',0)!=0),
            -1 if u['bullet'] is None else u['bullet'],int(u['spark']),0,','.join(map(str,pre[:0xc0])),','.join(map(str,post[:0xc0]))))
    L.append('};');L.append('#define VULCAN_SOURCES "%s"'%' '.join(srcs))
    (ROOT/'build').mkdir(exist_ok=True);(ROOT/'build/vulcan_fixture.h').write_text('\n'.join(L)+'\n')
    print(len(d['updates']),'turret updates')
if __name__=='__main__':main()
