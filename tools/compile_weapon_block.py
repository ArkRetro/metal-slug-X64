#!/usr/bin/env python3
"""Compile data/weapon_block_fixture.json.gz (tools/extract_weapon_block.py)
into build/weapon_block_fixture.h for tools/test_marco_weapons.c."""
import argparse,gzip,json
from pathlib import Path
ap=argparse.ArgumentParser();ap.add_argument('--fixture',default='data/weapon_block_fixture.json.gz')
ap.add_argument('--output',default='build/weapon_block_fixture.h');a=ap.parse_args()
d=json.loads(gzip.decompress(Path(a.fixture).read_bytes()))
KIND={'grant':1,'bombs':2,'expire':3,'life':4,'fire':5,'throw':6,'vehicle_throw':7,'armed':8,'landed':9,'release':10,'denied':11,'death':12}
L=['/* Generated by tools/compile_weapon_block.py; do not edit. */']
runs=[]
for r in d['runs']:
    n=r['run']
    L.append('static const weapon_step_t %s_steps[]={'%n)
    for s in r['steps']:
        ev=','.join('{%d,%d}'%(KIND[e[0]],e[1] if len(e)>1 else 0) for e in s['events']) or '{0,0}'
        h=lambda x:','.join('0x%s'%x[i:i+2] for i in range(0,len(x),2))
        L.append('{%d,{%s},{%s},{%s},%d,%d,%d,(const weapon_event_t[]){%s}},'%(s['frame'],h(s['before']),h(s['after']),h(s['slot']),
            s['f93'],s['f5f'],len(s['events']),ev))
    L.append('};');runs.append(n)
L.append('static const weapon_run_t weapon_runs[]={'+','.join('{"%s",%s_steps,sizeof(%s_steps)/sizeof(%s_steps[0])}'%(n,n,n,n) for n in runs)+'};')
Path(a.output).parent.mkdir(parents=True,exist_ok=True);Path(a.output).write_text('\n'.join(L)+'\n')
