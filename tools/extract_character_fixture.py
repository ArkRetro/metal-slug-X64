#!/usr/bin/env python3
"""Pose-by-pose fixture of a character (tools/test_character.c) from its own
MAME 0.264 catalog captures (run_marco_catalog.py --character N: chosen at
SOLDIER SELECT with the controller): the cases of Marco's fixture
(data/marco_throw_fixture.json, tools/extract_throw_fixture.py) with the
same capture plans and input cases, and the program chain of each case
replaced by the character's programs of the same table rows
(tools/export_character.py --report). Capture RAM only.
Usage: extract_character_fixture.py --character N --report build/chars/cN.json
         --captures /home/user/captures-chars --output data/character_fixture_cN.json
       extract_character_fixture.py --from-json data/character_fixture_cN.json --header build/character_fixture_cN.h"""
import argparse,json
from pathlib import Path
from extract_throw_fixture import steps,SITUATIONS
ROOT=Path(__file__).resolve().parents[1]
CAPTURE={'marco-cat1':'cat'}   # marco-X -> cN-X otherwise
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--character',type=int);p.add_argument('--report',type=Path)
    p.add_argument('--captures',type=Path);p.add_argument('--output',type=Path);p.add_argument('--from-json',type=Path);p.add_argument('--header',type=Path)
    a=p.parse_args()
    if a.from_json:d=json.loads(a.from_json.read_text())
    else:
        program={r['marco']:r['program'] for r in json.loads(a.report.read_text())['roles']}
        marco=json.loads((ROOT/'data/marco_throw_fixture.json').read_text())['cases'];cases=[];skipped=[];cache={}
        for m in marco:
            capture=a.captures/('c%d-%s'%(a.character,CAPTURE.get(m['capture'],m['capture'].replace('marco-',''))))
            if not (capture/'audit.json').exists():skipped.append(dict(name=m['name'],reason='no audited capture '+capture.name));continue
            if capture not in cache:cache[capture]=(json.loads((capture/'plan.json').read_text())['cases'],json.loads((capture/'controller.json').read_text())['choices'],steps(capture))
            plan,choices,st=cache[capture];c=next(x for x in plan if x['name']==m['case']);part=m['part']
            chain=[program[x] for x in m['chain']]
            mine=[x['choice'] for x in choices if x['choice']['part']==part and c['first']<=x['choice']['frame']<=c['last']+40]
            start=next((x['frame'] for x in mine if x['program']==chain[0]),None)
            if start is None:skipped.append(dict(name=m['name'],reason='program %06X not chosen in %s:%s'%(chain[0],capture.name,m['case'])));continue
            end=next((x['frame'] for x in mine if x['frame']>start and (x['program'] not in chain or x['program']==chain[0])),c['last']+1)
            seq=[st[(f,part)][0] if st.get((f,part)) else 0 for f in range(start,end) if (f,part) in st]
            assert seq and seq[0],(m['name'],start)
            cases.append(dict(name=m['name'],capture=capture.name,case=m['case'],part=part,chain=chain,form=m['form'],situation=m['situation'],first=start,descriptors=seq))
        d=dict(source='MAME 0.264 catalog captures of character %d chosen at SOLDIER SELECT by inputs (paired/controller traces)'%a.character,character=a.character,cases=cases,skipped=skipped)
        a.output.write_text(json.dumps(d,indent=0)+'\n')
        for s in skipped:print('skipped',s['name'],s['reason'])
    if a.header:
        n=d['character'];cases=[];desc=[]
        for c in d['cases']:
            cases.append('{"%s",%d,%d,%d,0x%x,%d,%d}'%(c['name'],c['part'],c['form'],SITUATIONS.index(c['situation']),c['chain'][0],len(desc),len(c['descriptors'])))
            desc+=['0x%x'%x for x in c['descriptors']]
        a.header.parent.mkdir(parents=True,exist_ok=True)
        a.header.write_text('/* Generated by tools/extract_character_fixture.py. */\n#define CHARACTER%d_CASES %d\nstatic const throw_case_t character%d_cases[]={%s};\nstatic const unsigned character%d_descriptors[]={%s};\n'%(n,len(cases),n,',\n'.join(cases) or '{0}',n,','.join(desc) or '0'))
    print(len(d['cases']),'cases',sum(len(c['descriptors']) for c in d['cases']),'steps',len(d.get('skipped',[])),'skipped')
if __name__=='__main__':main()
