#!/usr/bin/env python3
"""Fat Marco's shots (docs/MISSION3_DEBUG.md G21) from tools/capture_fat_weapons.lua
captures (fat.txt): every projectile, flash and grenade the fat player (+93 = 2)
creates, with the player of that frame (routine, +15, +72/+74, +90, +92) and
the node's birth position relative to the player's +28/+2C (pixels, y up)
and +6E; and the fat walks (routine 0C2888) update by update (+74). Births
farther than 64 pixels (a slot whose position is set later) are left out.
Capture RAM only.
Usage: extract_fat_muzzle_fixture.py OUT.json CAPTURE...
       extract_fat_muzzle_fixture.py --header IN.json OUT.h"""
import json,sys
from pathlib import Path
SHOTS={0x1b62c,0x1b668,0x1bdd2,0x63aee,0x63b22,0x63f10,0x646c8,0x646e0,0xa7226,0xa719c,0xa7960,0xde4fe,0xc58d2,0x1beda,0x1bea4,0x1e680,0x1e69c,0x1c362,0x1c334}
def s16(v):return v-65536 if v>=32768 else v
def b(h,o,n=1):return int(h[2*o:2*o+2*n],16)
def extract(caps):
    births=[];walks=[]
    for cap in caps:
        P={};lines=open(Path(cap)/'fat.txt').read().split('\n')
        for l in lines:
            t=l.split()
            if t and t[0]=='P':P[int(t[1])]=t[3]
        for l in lines:
            t=l.split()
            if not t or t[0]!='N':continue
            r,old=int(t[4],16),int(t[3],16)
            if r not in SHOTS or old in SHOTS:continue
            f=int(t[1]);h=t[5];p=P.get(f)
            if not p or b(p,0x93)!=2:continue
            dx=s16(b(h,0x28,2))-s16(b(p,0x28,2));dy=s16(b(h,0x2c,2))-s16(b(p,0x2c,2))
            if abs(dx)>64 or abs(dy)>64:continue
            births.append([Path(cap).name,f,r,b(p,0,4),b(p,0x15)&1,b(p,0x90),b(p,0x92),s16(b(p,0x72,2)),s16(b(p,0x74,2)),b(h,0x6e),dx,dy])
        # Walks: the player's updates are every second frame (states change in pairs).
        fs=sorted(P);run=[]
        for f in fs+[None]:
            p=P.get(f) if f is not None else None
            if p and b(p,0,4)==0xc2888 and b(p,0x93)==2 and (not run or f==run[-1][0]+1):run.append((f,s16(b(p,0x74,2))));continue
            if len(run)>=8:
                # The update frames: the parity of the first pose change (+77).
                ch=next(i for i in range(1,len(run)) if b(P[run[i][0]],0x77)!=b(P[run[i-1][0]],0x77))
                k=ch%2;walks.append([Path(cap).name,run[k][0],[y for _,y in run[k::2]]])
            run=[]
    return dict(source=' '.join(Path(c).name for c in caps),births=births,walks=walks)
def header(src,out):
    d=json.load(open(src));L=['/* Generated by tools/extract_fat_muzzle_fixture.py --header from %s. */'%Path(src).name,
        'typedef struct { unsigned frame; uint32_t ctor,routine; uint8_t left,f90,f92; int8_t x72,y74; uint8_t angle; int16_t dx,dy; } fat_birth_t;',
        'static const fat_birth_t fat_births[]={']
    for r in d['births']:L.append('{%d,0x%x,0x%x,%d,0x%x,0x%x,%d,%d,0x%x,%d,%d},'%tuple(r[1:]))
    L+=['};','#define FAT_BIRTHS (sizeof fat_births/sizeof fat_births[0])','typedef struct { unsigned frame,count; const int8_t *y74; } fat_walk_t;']
    for i,w in enumerate(d['walks']):L.append('static const int8_t fat_walk%d[]={%s};'%(i,','.join(map(str,w[2]))))
    L.append('static const fat_walk_t fat_walks[]={'+','.join('{%d,%d,fat_walk%d}'%(w[1],len(w[2]),i) for i,w in enumerate(d['walks']))+'};')
    L.append('#define FAT_WALKS (sizeof fat_walks/sizeof fat_walks[0])')
    Path(out).write_text('#include <stdint.h>\n'+'\n'.join(L)+'\n')
if __name__=='__main__':
    if sys.argv[1]=='--header':header(sys.argv[2],sys.argv[3])
    else:
        d=extract(sys.argv[2:]);json.dump(d,open(sys.argv[1],'w'),separators=(',',':'))
        print(len(d['births']),'births',len(d['walks']),'walks ->',sys.argv[1])
