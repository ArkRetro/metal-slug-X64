#!/usr/bin/env python3
"""The mummy (form 3) update by update from the marco-mz2 catalog capture
(tools/mame/run_marco_catalog.py --give-mummy --command-trace
--controller-trace): for every player update, the situation the port's
gameplay gives marco_visual.c (derived from the original controller state
and the inputs) and the descriptors the original drew for the body and the
weapon part (MARCO_DRAW, 0 for none). tools/test_marco_visual.c replays it.

Situation of update u (frame f, the controller routine of states.jsonl at
f+2 = the state after the update):
  transforming  routine 0C17A0/0C17F0 at f (0C182A ends it in the update)
  takeoff       state after = 0C1A0C (0C19E4/0C1A0C, crouched before the jump)
  grounded      state after not 0C1A62 (the air): the port's player is on
                the ground during the takeoff and in the update it lands
  crouch        state after in the crouch states 0C1B2E..0C1D18
  fired         a fire program started (0C3A50 choice 25F5CA/25F89E/25F932)
                or the crouched shot 260C8A (MARCO_INIT)
  thrown        the grenade program 25F626 chosen
  aim_up        Up held; aim_down: Down held in the air or the takeoff
  moving        Left/Right held, not crouched and the update not run by the
                takeoff 0C1A0C or the landing 0C1AC8/0C1ADE (+62 = 0 there:
                gameplay.c zeroes the direction)
  facing        +15 bit 0 after the update (states flags bit 0: 1 = left)
"""
import argparse,json,re
from pathlib import Path
AIR={0xC1A62};TAKEOFF={0xC1A0C};CROUCH={0xC1B2E,0xC1B66,0xC1B80,0xC1BC8,0xC1BDA,0xC1CCC,0xC1CF8,0xC1CB0}
TRANSFORM={0xC17A0,0xC17F0};LANDING={0xC1AC8,0xC1ADE}
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('capture',type=Path,nargs='?');p.add_argument('--output',type=Path)
    p.add_argument('--first',type=int,default=2101);p.add_argument('--last',type=int,default=5049)
    p.add_argument('--from-json',type=Path,help='write the C header of a stored fixture');p.add_argument('--header',type=Path)
    a=p.parse_args();c=a.capture
    if a.from_json:
        steps=json.loads(a.from_json.read_text())['steps'];b=lambda v:'1' if v else '0'
        rows=[f"{{{b(s['transforming'])},{b(s['takeoff'])},{b(s['grounded'])},{b(s['crouch'])},{b(s['fired'])},{b(s['thrown'])},{b(s['aim_up'])},{b(s['aim_down'])},{b(s['moving'])},{s['facing']},{s['body']}u,{s['weapon']}u}}," for s in steps]
        a.header.write_text('/* Generated by tools/extract_mummy_fixture.py from data/marco_mummy_fixture.json (marco-mz2). */\n'
            'typedef struct {bool transforming,takeoff,grounded,crouch,fired,thrown,aim_up,aim_down,moving;int facing;uint32_t body,weapon;} mummy_step_t;\n'
            f'#define MUMMY_STEPS {len(steps)}u\nstatic const mummy_step_t mummy_steps[MUMMY_STEPS]={{\n'+'\n'.join(rows)+'\n};\n')
        return
    states={};held={};cur={}
    for l in open(c/'states.jsonl'):
        d=json.loads(l);states[d['frame']]=d
    ev=sorted((json.loads(l) for l in open(c/'inputs.jsonl')),key=lambda d:d['frame'])
    text=(c/'debug.log').read_text()
    draws={};inits={};choices={}
    for m in re.finditer(r'MARCO_DRAW frame=(\d+) descriptor=([0-9A-F]+)',text):draws.setdefault(int(m.group(1)),[]).append(int(m.group(2),16))
    for m in re.finditer(r'MARCO_INIT frame=(\d+) program=([0-9A-F]+)',text):inits.setdefault(int(m.group(1)),[]).append(int(m.group(2),16))
    for m in re.finditer(r'MARCO_PROGRAM_CHOICE frame=(\d+) part=1 \S+ \S+ program=([0-9A-F]+)',text):choices.setdefault(int(m.group(1)),[]).append(int(m.group(2),16))
    # body/weapon split: MARCO_DRAW lines follow MARCO_STEP_IN of the part's state
    parts={}
    part=None
    for line in text.splitlines():
        if line.startswith('MARCO_STEP_IN '):part='w' if 'state=0010154C' in line else 'b'
        elif line.startswith('MARCO_DRAW '):
            m=re.match(r'MARCO_DRAW frame=(\d+) descriptor=([0-9A-F]+)',line);f=int(m.group(1))
            parts.setdefault(f,{}).setdefault(part,int(m.group(2),16))
    steps=[];k=0
    for f in range(a.first,a.last+1,2):
        while k<len(ev) and ev[k]['frame']<=f:held[ev[k]['button']]=ev[k]['value'];k+=1
        after=states[f+1]['routine'] if f+1 in states else states[f]['routine']
        nxt=states.get(f+2,{}).get('routine',after)
        crouch=nxt in CROUCH
        ch=choices.get(f,[]);ini=inits.get(f,[])
        s=dict(frame=f,transforming=states[f]['routine'] in TRANSFORM and nxt!=0xC18B4 or states[f]['routine']==0xC17A0,
               takeoff=nxt in TAKEOFF,grounded=nxt not in AIR,crouch=crouch,
               fired=any(x in (0x25F5CA,0x25F89E,0x25F932) for x in ch) or 0x260C8A in ini,thrown=0x25F626 in ch,
               aim_up=bool(held.get('P1 Up')),aim_down=bool(held.get('P1 Down')) and nxt in AIR|TAKEOFF,
               moving=bool(held.get('P1 Left') or held.get('P1 Right')) and not crouch and states[f]['routine'] not in TAKEOFF|LANDING,
               facing=-1 if states.get(f+2,states[f])['flags']&1 else 1,
               body=parts.get(f,{}).get('b',0),weapon=parts.get(f,{}).get('w',0))
        steps.append(s)
    a.output.write_text(json.dumps(dict(source='MAME 0.264 marco-mz2 (run_marco_catalog.py --give-mummy), tools/extract_mummy_fixture.py',steps=steps),separators=(',',':'))+'\n')
    print('mummy steps',len(steps))
if __name__=='__main__':main()
