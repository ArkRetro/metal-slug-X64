#!/usr/bin/env python3
"""The fade step table of the sound driver (M1 0x0700..0x07FF, read by 4FAF: F806 = 16 * [0x0700 + xx - 0x20]) into
data/music_fade.json; with --header, that file into build/music_fade.h (src/game_audio.c)."""
import json,sys,zipfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
if sys.argv[1:2]==['--header']:
    d=json.loads((ROOT/'data/music_fade.json').read_text());t=bytes.fromhex(d['hex'])
    (ROOT/'build').mkdir(exist_ok=True)
    (ROOT/'build/music_fade.h').write_text('/* Generated by tools/extract_music_fade.py; do not edit. M1 0x0700. */\n'
        'static const uint8_t music_fade_table[256]={%s};\n'%','.join(str(b) for b in t))
else:
    m=zipfile.ZipFile(sys.argv[1]).read('250-m1.m1')
    (ROOT/'data/music_fade.json').write_text(json.dumps(dict(source='250-m1.m1 0x0700..0x07FF (4FAF)',hex=m[0x700:0x800].hex()))+'\n')
