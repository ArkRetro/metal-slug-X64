#!/usr/bin/env python3
"""Upper-body throw/fire fixture (src/marco_visual.c, tools/test_marco_visual.c)
from Marco catalog captures (tools/mame/run_marco_catalog.py --paired-trace
--controller-trace): for each named case, the part (body 1014E4 / weapon
10154C) and the program chain, the descriptors that part drew in every step
(MARCO_DRAW between its MARCO_STEP_IN/OUT) from the update where the original
selection (0C0F32/0C0F62) chose the first program of the chain, until it
chose a program outside the chain (or restarted its first one). Capture RAM only.
Usage: extract_throw_fixture.py --output data/marco_throw_fixture.json
       NAME=CAPTURE:CASE:PART:PROG[,PROG..][:FORM][:SITUATION] ...
       extract_throw_fixture.py --from-json data/marco_throw_fixture.json --header build/marco_throw_fixture.h"""
import argparse,json,re
from pathlib import Path
SITUATIONS=('stand','crouch','air','run')
def steps(capture):
    out={};part=None
    for line in (capture/'debug.log').read_text().splitlines():
        m=re.match(r'MARCO_STEP_IN frame=(\d+) state=([0-9A-F]+)',line)
        if m:part=(int(m.group(1)),0 if m.group(2)=='001014E4' else 1);out.setdefault(part,[]);continue
        if line.startswith('MARCO_STEP_OUT'):part=None;continue
        m=re.match(r'MARCO_DRAW frame=(\d+) descriptor=([0-9A-F]+)',line)
        if m and part:out[part].append(int(m.group(2),16))
    return out
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('cases',nargs='*');p.add_argument('--output',type=Path)
    p.add_argument('--from-json',type=Path);p.add_argument('--header',type=Path);a=p.parse_args()
    if a.from_json:d=json.loads(a.from_json.read_text())
    else:
        cases=[];cache={}
        for spec in a.cases:
            name,_,rest=spec.partition('=');f=rest.split(':');capture=Path(f[0]);case,part=f[1],int(f[2])
            chain=[int(x,16) for x in f[3].split(',')];form=int(f[4]) if len(f)>4 else 0;situation=f[5] if len(f)>5 else 'stand'
            assert situation in SITUATIONS
            if capture not in cache:cache[capture]=(json.loads((capture/'plan.json').read_text())['cases'],json.loads((capture/'controller.json').read_text())['choices'],steps(capture))
            plan,choices,st=cache[capture];c=next(x for x in plan if x['name']==case)
            mine=[x['choice'] for x in choices if x['choice']['part']==part and c['first']<=x['choice']['frame']<=c['last']+40]
            start=next(x['frame'] for x in mine if x['program']==chain[0])
            end=next((x['frame'] for x in mine if x['frame']>start and (x['program'] not in chain or x['program']==chain[0])),c['last']+1)
            seq=[st[(f,part)][0] if st.get((f,part)) else 0 for f in range(start,end) if (f,part) in st]
            assert seq and seq[0],(name,start)
            cases.append(dict(name=name,capture=capture.name,case=case,part=part,chain=chain,form=form,situation=situation,first=start,descriptors=seq))
        d=dict(source='MAME 0.264 Marco catalog captures (paired/controller traces)',cases=cases)
        a.output.write_text(json.dumps(d,indent=0)+'\n')
    if a.header:
        cases=[];desc=[]
        for c in d['cases']:
            cases.append('{"%s",%d,%d,%d,0x%x,%d,%d}'%(c['name'],c['part'],c['form'],SITUATIONS.index(c['situation']),c['chain'][0],len(desc),len(c['descriptors'])))
            desc+=['0x%x'%x for x in c['descriptors']]
        a.header.parent.mkdir(parents=True,exist_ok=True)
        a.header.write_text('/* Generated by tools/extract_throw_fixture.py. */\ntypedef struct {const char *name;int part,form,situation;unsigned program,first,count;} throw_case_t;\n#define THROW_CASES %d\nstatic const throw_case_t throw_cases[]={%s};\nstatic const unsigned throw_descriptors[]={%s};\n'%(len(cases),',\n'.join(cases),','.join(desc)))
    print(len(d['cases']),'cases',sum(len(c['descriptors']) for c in d['cases']),'steps')
if __name__=='__main__':main()
