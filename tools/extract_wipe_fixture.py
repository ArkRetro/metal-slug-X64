#!/usr/bin/env python3
"""Fixture of the stage transition actors 3AED8 (entry) and 3AEF0 (exit)
(src/neo_wipe.c) from a family trace of tools/capture_fullgame.lua
(MSX_FULL_FAMILY_ROOTS=3aed8,3aef0 MSX_FULL_VRAM_TRACE=1, docs/MISION2.md),
and its C header (--header).

Per update of a wipe node: frame, routine before, +72 before/after (none
after: deleted through 004188), the fix-map writes (Z lines: VRAM address
and data) and whether the update wrote the creator's +60 (1013C4)."""
import argparse,gzip,json
from pathlib import Path
ROOTS={0x3aed8,0x3aef0}
def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('trace',type=Path,nargs='?')
    ap.add_argument('--from-json',type=Path);ap.add_argument('--output',type=Path,required=True);ap.add_argument('--header',type=Path)
    a=ap.parse_args()
    if a.from_json:write_header(a,json.load(gzip.open(a.from_json))['updates']);return
    ups=[];cur=None;frame=0;nodes=set()
    for line in open(a.trace):
        t=line.split()
        if not t:continue
        if t[0]=='F':frame=int(t[1]);continue
        if t[0]=='U':
            if cur:ups.append(cur)
            n,r=int(t[1],16),int(t[2],16)
            if r in ROOTS:nodes.add(n)
            if n in nodes and (r in ROOTS or r in (0x3aee6,0x3aefe)):
                b=bytes.fromhex(t[3]);cur=dict(frame=frame,node=n,routine=r,pre=b[0x72]<<8|b[0x73],post=None,post_routine=None,z=[],signal=0)
            else:
                cur=None
                if n in nodes and r not in (0x3aee6,0x3aefe):nodes.discard(n)
            continue
        if cur is None:continue
        if t[0]=='V':b=bytes.fromhex(t[2]);cur['post']=b[0x72]<<8|b[0x73];cur['post_routine']=int.from_bytes(b[0:4],'big');ups.append(cur);cur=None
        elif t[0]=='Z':cur['z'].append([int(t[1],16),int(t[2],16)])
        elif t[0]=='W' and t[1]=='1013c4':cur['signal']=int(t[3],16)>>8
    if cur:ups.append(cur)
    with gzip.open(a.output,'wt') as f:json.dump(dict(source=f'MAME 0.264 mslugx euro family trace {a.trace}',updates=ups),f,separators=(',',':'))
    print(len(ups),'updates');write_header(a,ups)
def write_header(a,ups):
    if not a.header:return
    L=['/* Generated by tools/extract_wipe_fixture.py from data/wipe_fixture.json.gz. */','#include <stdint.h>',
       'typedef struct { uint32_t frame,routine,post_routine; int32_t pre,post; uint8_t signal; uint32_t z0,zn; } wipe_update_t;']
    zs=[];rows=[]
    for u in ups:
        rows.append('{%d,0x%X,0x%X,%d,%d,%d,%d,%d}'%(u['frame'],u['routine'],u['post_routine'] or 0,u['pre'],-1 if u['post'] is None else u['post'],u['signal'],len(zs),len(u['z'])))
        zs+=u['z']
    L.append('static const wipe_update_t wipe_updates[]={'+',\n'.join(rows)+'};')
    L.append('static const uint16_t wipe_z[][2]={'+','.join('{0x%X,0x%X}'%(x,y) for x,y in zs)+'};')
    a.header.write_text('\n'.join(L)+'\n')
if __name__=='__main__':main()
