#!/usr/bin/env python3
"""The turns of the main loop in a capture of the pause 015520
(tools/mame/capture_pause.lua, pause.csv) as data/pause_fixture.json
(--extract CSV), and that JSON as build/pause_fixture.h (--header).
A turn is a change of the update count 10000E or of the blink 10C2C2: the
row holds the RAM after the turn (docs/PAUSA.md)."""
import argparse,csv,json
from pathlib import Path
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--extract',type=Path);p.add_argument('--json',type=Path,required=True);p.add_argument('--header',type=Path)
a=p.parse_args()
if a.extract:
    rows=list(csv.reader(a.extract.open()))
    assert all(len(r)==50 for r in rows)
    # columns: frame, select line, 10C2BC..BF, 10C2C2, 10008D, 10008E, 100012, 100013, 10128A, 10133A, 10FDB6, 10C366, 10C367, 10992C,
    # 20 words from 10991A, six fix cells from 725A (step 0x20), 10000E, palette words
    turns=[];prev=None
    for r in rows:
        key=(r[43],r[6])
        if prev is not None and key!=prev:
            turns.append(dict(frame=int(r[0]),select=int(r[15],16),owner=int(r[5],16),blink=int(r[6],16),last=int(r[7],16),resumed=int(r[8],16),
                fade=[int(x,16) for x in r[17:23]],count=int(r[16],16),lspc=[int(r[9],16),int(r[10],16)],cells=[int(x,16) for x in r[37:42]]))
        prev=key
    f=rows[0]
    assert all(int(r[3],16)==0 and int(r[4],16)==0 and int(r[2],16)==0 and int(r[13],16)==1 for r in rows),'10C2BC/BD/BE clear, mode 1'
    doc=dict(source='MAME 0.264, mslugx, state u1020 of the TAS, RAM 10FD82 = 0 written, SELECT (380000 bit 1) pressed twice',
        before=[int(x,16) for x in f[37:42]],fade0=[int(x,16) for x in f[17:26]],lspc0=[int(f[9],16),int(f[10],16)],turns=turns)
    a.json.write_text(json.dumps(doc,separators=(',',':')).replace('},{','},\n{')+'\n')
    print(len(turns),'turns,',sum(1 for t in turns if not t['last']),'paused')
if a.header:
    d=json.loads(a.json.read_text());t=d['turns']
    out=['/* Generated by tools/pause_fixture.py from data/pause_fixture.json. */','#include <stdint.h>',
        'typedef struct {uint8_t select,owner,blink,last,resumed,count;uint16_t fade[6];uint8_t lspc[2];uint16_t cells[5];} pause_fixture_turn_t;',
        '#define PAUSE_FIXTURE_TURNS %d'%len(t),
        'static const uint16_t pause_fixture_before[5]={%s};'%','.join(map(str,d['before'])),
        'static const uint16_t pause_fixture_fade0[9]={%s};'%','.join(map(str,d['fade0'])),
        'static const uint8_t pause_fixture_lspc0[2]={%s};'%','.join(map(str,d['lspc0'])),
        'static const pause_fixture_turn_t pause_fixture[PAUSE_FIXTURE_TURNS]={']
    for x in t:out.append(' {%d,%d,%d,%d,%d,%d,{%s},{%s},{%s}},'%(x['select'],x['owner'],x['blink'],x['last'],x['resumed'],x['count'],','.join(map(str,x['fade'])),','.join(map(str,x['lspc'])),','.join(map(str,x['cells']))))
    out.append('};');a.header.parent.mkdir(parents=True,exist_ok=True);a.header.write_text('\n'.join(out)+'\n')
